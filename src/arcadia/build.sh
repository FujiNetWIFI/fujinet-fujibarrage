#!/usr/bin/env bash
# build.sh -- FujiBarrage for the Emerson Arcadia 2001: a protocol 2
# (APPBANK) image -- page 0's 8K (fixed A, RAM-L, fixed B, RAM-H; the
# mailbox empty and claimed) and NPAGES-1 more pages of 2K (barrage.asm).
# FujiBlast's src/arcadia/build.sh; the page model, the linker and the
# checks are M.U.L.E.'s clients/arcadia (tools/arc/).
#
#   src/arcadia/build.sh                r2r/arcadia/barrage.bin
#   OUT=dir R2R=dir                     where the objects and the image go
#   DEFSRV=host:port                    the server without the lobby's key
#                                       (default gen/server, never rewritten here)
#
# Needs Macroassembler AS (~/asl/asl and p2bin, or ASL=/P2BIN=) and Go (the
# server's CATALOG, kept in ROM: tools/arc/mkcat_arc.py).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/arcadia}"
R2R="${R2R:-$ROOT/r2r/arcadia}"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
T="$ROOT/tools/arc"
mkdir -p "$OUT" "$R2R"
OUT="$(cd "$OUT" && pwd)"
R2R="$(cd "$R2R" && pwd)"

# the protocol's numbers, as the Makefile writes them for the other ports
sed -n 's/^#define \([A-Z_0-9]*\) *\([0-9][0-9]*\)$/\1 EQU \2/p' "$ROOT/src/proto.h" > "$OUT/proto.inc"
python3 "$T/mksnd_arc.py" "$OUT/sndequ.inc" "$OUT/sndtab.inc" "$OUT/snddat.inc" "$OUT/sndtit.inc"
python3 "$T/mktank_arc.py" "$OUT/tank.inc"
( cd "$ROOT/server" && go run ./cmd/barraged -catalog "$OUT/catalog.bin" )
python3 "$T/mkcat_arc.py" "$OUT/catalog.bin" "$OUT/cat.inc" "$OUT/catequ.inc" "$OUT/catset.inc" "$OUT/catitem.inc"
python3 "$T/mkstate_arc.py" "$ROOT/src/proto.h" "$OUT/catequ.inc" "$OUT/state.inc"
DEFSRV="${DEFSRV:-$(cat "$ROOT/gen/server" 2>/dev/null || echo fujinet.online:9913)}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'DEFSPEC: DB      "N:TCP://%s/",0\n' "$DEFSRV"
  printf 'DEFURL:  DB      "tcp://%s/?table=",0\n' "$DEFSRV"
} > "$OUT/config.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  true
} > "$OUT/flags.inc"
NPAGES=$(sed -n 's/^NPAGES *EQU *\([0-9]*\).*/\1/p' "$HERE/src/pages.inc")

for p in $(seq 0 $((NPAGES - 1))); do
    printf '; GENERATED by build.sh -- do not edit.\nPAGE EQU %d\n        INCLUDE "barrage.asm"\n' "$p" \
        > "$OUT/bb_p$p.asm"
    "$ASL" -q -L -U -i "$HERE" -i "$OUT" -o "$OUT/bb_p$p.p" -olist "$OUT/bb_p$p.lst" "$OUT/bb_p$p.asm"
    "$P2BIN" "$OUT/bb_p$p.p" "$OUT/bb_p$p.flat" -r '$0000-$2FFF' -l 0 >/dev/null
done
python3 "$T/mkblast.py" "$OUT" bb "$NPAGES" "$R2R/barrage.bin"
# the 2650's return stack is 8 deep and silently wraps: keep one spare
python3 "$T/checkdepth.py" --max 7 "$HERE/src/pages.inc" "$OUT"/bb_p*.lst
# a register read after a cart-RAM write (or another clobbering service)
python3 "$T/checkclob.py" "$HERE"/src/*.inc
# a conditional branch testing a LODI's constant
python3 "$T/checkcc.py" "$HERE"/src/*.inc
# the RAM ledger: every zone within its bounds, nothing kept where a screen clears
python3 "$T/checkram.py" "$OUT/bb_p0.lst"
