#!/usr/bin/env python3
"""mklook_astro.py OUT.inc -- the Astrocade's colour tables from
tools/astroart.py, for the resident half (the raster reads them whatever
page is mapped): SKYTAB (a sky's 14 bands, then 2 for the bars' bands: 16
a sky), DIRTTAB, DIRTLIT, SEATC, SEATTX (the HUD's text on each seat's
colour), FIRECYC, and the EQUs of the rest."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import astroart as A


def db(name, vals):
    return "%s:\n        DB      %s" % (name, ",".join("0%02XH" % v for v in vals)) if name else \
        "        DB      %s" % ",".join("0%02XH" % v for v in vals)


def main(out):
    lines = ["; GENERATED by tools/astro/mklook_astro.py from tools/astroart.py -- do not edit.",
             "SKYTAB:"]
    for name, sky in zip(A.SKY_NAMES, A.SKIES):
        assert len(sky) == A.NFB, name
        lines.append(db(None, sky + [sky[-1], sky[-1]]) + "    ; " + name)
    lines += [db("DIRTTAB", A.DIRT), db("DIRTLIT", A.DIRT_LIT), db("SEATC", A.SEATS),
              db("SEATTX", [0x00 if c in A.LIGHT else 0x07 for c in A.SEATS]),
              db("FIRECYC", A.FIRE),
              "FIRESTL EQU     0%02XH" % A.FIRE_STILL,
              "HUDR0   EQU     0%02XH" % A.HUD_RIGHT[0],
              "HUDR1   EQU     0%02XH" % A.HUD_RIGHT[1],
              "C_POWER EQU     0%02XH" % A.BAR_POWER,
              "C_ENERGY EQU    0%02XH" % A.BAR_ENERGY,
              "C_TROUGH EQU    0%02XH" % A.BAR_TROUGH]
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
