#!/usr/bin/env python3
"""gen_spike.py -- scene.inc for spike.asm and the frame arcmodel.py says it
shows (expected.png, 192x262): one mock-up frame (mock_arc.Mock).
  gen_spike.py OUTDIR DUMP.dmp FRAME LOOK PALETTE WEAPON"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import arcmodel as A  # noqa: E402
import mock_arc as M  # noqa: E402


def db(name, data):
    out = [name + ":"]
    for i in range(0, len(data), 16):
        out.append("        DB      " + ",".join("$%02X" % b for b in data[i:i + 16]))
    return "\n".join(out) + "\n"


def main(out, dump, k, look, palette, weapon):
    fs = M.frames(dump)
    k = int(k)
    u, *_ = M.Mock(look, palette).build(fs[k], k, M.hud_for(fs[k], int(weapon)))
    m = u.m
    s = "; GENERATED by gen_spike.py -- do not edit.\n"
    for r in (0xFC, 0xFD, 0x1F8, 0x1F9, 0x1FA, 0x1FB):
        s += "R%04X   EQU     $%02X\n" % (0x1800 + r, m[r])
    s += "        ORG     $0C00\n"
    s += db("SCRA", m[0:0xD0]) + db("SCRB", m[0x200:0x2D0]) + db("UDCS", m[0x180:0x1A0]) + db("SPRS", m[0xF0:0xF8])
    open(os.path.join(out, "scene.inc"), "w").write(s)
    A.to_image(u.frame()).save(os.path.join(out, "expected.png"))


if __name__ == "__main__":
    main(*sys.argv[1:])
