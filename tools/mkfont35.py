#!/usr/bin/env python3
"""mkfont35.py gfx/font3x5.txt OUT.h -- the 3x5 font as a C table:
font35[c - 32] (field.c has it; bln.s reads it), a glyph in 15 bits: row r in bits 3r+2..3r, the columns
left to right (bit 2 the left); characters missing from the master are
blank."""
import sys
glyphs, cur = {}, None
for line in open(sys.argv[1]):
    line = line.rstrip('\n')
    if line.startswith('# '):
        continue
    if line.startswith('char '):
        cur = line[5:6]
        glyphs[cur] = []
        continue
    if cur is not None and len(line) == 3 and len(glyphs[cur]) < 5:
        glyphs[cur].append(sum(4 >> i for i in range(3) if line[i] == '#'))
with open(sys.argv[2], 'w') as f:
    f.write("/* GENERATED by tools/mkfont35.py from gfx/font3x5.txt. */\n")
    f.write("const uint16_t font35[64] = {\n")
    for c in range(32, 96):
        g = glyphs.get(chr(c), [0] * 5)
        f.write("    0x%04X,  /* %r */\n" % (sum(v << (3 * r) for r, v in enumerate(g)), chr(c)))
    f.write("};\n")
