#!/usr/bin/env python3
"""mkfar.py -- the 5200 game's far calls (tools/atari5200/far.txt).

    mkfar.py far.txt OUT.s          the wrappers, in the core
    mkfar.py far.txt --defs BANK    cc65's -D flags for an overlay of BANK:
                                    its functions renamed ovl_<name>

A wrapper keeps the fastcall argument (A/X), notes the bank that was in,
picks the overlay's (a read of $BFD0 + 4n: src/atari5200/bank.s's
far_go), calls it, picks the old one again and returns its result (A/X).
Interrupts never switch banks, and the core is the same in every bank.
"""
import sys


def entries(path):
    out = []
    for line in open(path):
        line = line.split("#")[0].split()
        if line:
            out.append((int(line[0]), line[1]))
    return out


def main():
    ent = entries(sys.argv[1])
    if sys.argv[2] == "--defs":
        b = int(sys.argv[3])
        print(" ".join("-D%s=ovl_%s" % (n, n) for bank, n in ent if bank == b))
        return
    s = ["; GENERATED by tools/atari5200/mkfar.py from far.txt: do not edit.",
         "        .import far_go, far_bank",
         "        .importzp far_a",
         ""]
    s += ["        .import _ovl_%s" % n for _, n in ent]
    s += ["        .export _%s" % n for _, n in ent]
    s += ["", "        .code"]
    for b, n in ent:
        s += ["_%s:" % n,
              "        sta     far_a",
              "        lda     far_bank",
              "        pha",
              "        lda     #%d" % b,
              "        jsr     far_go",
              "        lda     far_a",
              "        jsr     _ovl_%s" % n,
              "        sta     far_a",
              "        pla",
              "        jsr     far_go",
              "        lda     far_a",
              "        rts"]
    open(sys.argv[2], "w").write("\n".join(s) + "\n")


if __name__ == "__main__":
    main()
