#!/usr/bin/env bash
# build.sh -- FujiBarrage for the Bally Astrocade: a protocol 2 (APPBANK)
# image -- the 8K window (page 0, the resident half, the mailbox clear and
# claimed) and NPAGES-2 more pages of 4K (barrage.asm). FujiBlast's
# src/astrocade/build.sh, for this tree.
#
#   src/astrocade/build.sh              r2r/astrocade/barrage.bin
#   OUT=dir R2R=dir                     where the objects and the image go
#   DEFSRV=host:port                    the server without the lobby's key
#                                       (default gen/server, never rewritten here)
#
# Needs zmac 1.3's source (~/Workspace/zmac-1.3, or ZMACSRC=): zmac holds
# 2000 symbols and this program has more, so the build makes its own copy
# with a bigger table (build/zmac/zmac).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/astrocade}"
R2R="${R2R:-$ROOT/r2r/astrocade}"
T="$ROOT/tools/astro"
mkdir -p "$OUT" "$R2R"
OUT="$(cd "$OUT" && pwd)"

ZMAC="${ZMAC:-$ROOT/build/zmac/zmac}"
if [ ! -x "$ZMAC" ]; then
    src=""
    for d in "${ZMACSRC:-}" "$HOME/Workspace/zmac-1.3" "$HOME/Workspace/fujinet-firmware/pico/astrocade/tools/zmac"; do
        if [ -n "$d" ] && [ -f "$d/zmac.c" ] && [ -f "$d/mio.c" ]; then src="$d"; break; fi
    done
    [ -n "$src" ] || { echo "build.sh: no zmac 1.3 source; set ZMACSRC=" >&2; exit 1; }
    mkdir -p "$ROOT/build/zmac/src"
    cp "$src"/*.c "$src"/*.h "$ROOT/build/zmac/src/"
    sed -i 's/^#define ITEMTABLESIZE.*/#define ITEMTABLESIZE 16000/' "$ROOT/build/zmac/src/zmac.c"
    (cd "$ROOT/build/zmac/src" && gcc -O -o ../zmac zmac.c mio.c getoptn.c)
fi

python3 "$T/mkproto.py" "$ROOT/src/proto.h" "$OUT/proto.inc"
python3 "$T/mklook_astro.py" "$OUT/look.inc"
python3 "$T/mktab_astro.py" "$OUT/tables.inc"
python3 "$T/mksnd_astro.py" "$OUT/snd.inc" >/dev/null   # the sounds (and music/*.txt)
# each drawing page its own copy of the pixel primitives (zmac's labels are
# global: the FP_ prefix renamed), and of their tables
for pp in PY OQ; do
    sed "s/FP_/${pp}_/g" "$HERE/src/fld.inc" > "$OUT/fld_$(echo $pp | tr A-Z a-z).inc"
    python3 "$T/mktab_astro.py" "$OUT/tables_$(echo $pp | tr A-Z a-z).inc" "${pp}_"
done
sed "s/FP_/PY_/g" "$HERE/src/ell.inc" > "$OUT/ell_py.inc"
sed "s/FP_/OQ_/g" "$HERE/src/ell.inc" > "$OUT/ell_oq.inc"
sed "s/FP_/OQ_/g" "$HERE/src/solver.inc" > "$OUT/solver_oq.inc"
python3 "$T/mkfont_astro.py" "$ROOT/gfx/font3x5.txt" "$OUT/font35.inc"
cp "$HERE/test/fixture.inc" "$OUT/fixture.inc"
( cd "$ROOT/server" && go run ./cmd/barraged -catalog "$OUT/catalog.bin" )
python3 "$T/mkcat_astro.py" "$OUT/catalog.bin" "$OUT/cat.inc"
DEFSRV="${DEFSRV:-$(cat "$ROOT/gen/server" 2>/dev/null || echo fujinet.online:9913)}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'DEFSPEC: DB      "N:TCP://%s/",0\n' "$DEFSRV"
  printf 'DEFURL:  DB      "tcp://%s/?table=",0\n' "$DEFSRV"
} > "$OUT/config.inc"

ln -sfn "$HERE" "$OUT/srcdir"
(cd "$OUT" && "$ZMAC" -o barrage.raw -x barrage.lst srcdir/barrage.asm)
if grep -q "^[0-9]* errors" "$OUT/barrage.lst" && ! grep -q "^0 errors" "$OUT/barrage.lst"; then
    grep -B2 -A2 "^[A-Za-z] " "$OUT/barrage.lst" | head -40 >&2
    echo "build.sh: zmac reported errors (see $OUT/barrage.lst)" >&2
    exit 1
fi

# the image: 8K + (NPAGES-2) x 4K (page 1 is the window's high half)
npages=$(sed -n 's/^NPAGES *EQU *\([0-9]*\).*/\1/p' "$HERE/src/pages.inc")
IMAGE=$((8192 + (npages - 2) * 4096))
size=$(wc -c < "$OUT/barrage.raw")
if [ "$size" -gt "$IMAGE" ]; then
    echo "build.sh: the assembly is $size bytes, over the $IMAGE image" >&2
    exit 1
fi
{
    cat "$OUT/barrage.raw"
    head -c $((IMAGE - size)) /dev/zero
} > "$R2R/barrage.bin"
printf 'FUJI' | dd of="$R2R/barrage.bin" bs=1 seek=$((0x1CFC)) conv=notrunc status=none

python3 "$T/checkrom.py" --banked "$R2R/barrage.bin"
python3 "$T/checksize.py" "$OUT/barrage.lst"
python3 "$T/checkcalls.py" "$OUT/barrage.lst"
