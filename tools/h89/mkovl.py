#!/usr/bin/env python3
"""mkovl.py OUT.asm NAME... -- the stubs for the HDOS build's overlay entry
points (src/h89/ovl.asm): each NAME is OVERLAY:function, and becomes a
resident `_function: call ovl_tramp; defq _function_ovl`, where the overlay's
own copy of the function was compiled as function_ovl (-Dfunction=function_ovl).
OVERLAY is the number in src/h89/mmap.inc's order (room 1, field 2)."""
import sys

NUM = {"room": 1, "field": 2}      # (the overlay's number is in its address: mmap.inc's org)

out = ["; GENERATED by tools/h89/mkovl.py: the overlay entry points' stubs.",
       "        SECTION code_user",
       "        EXTERN  ovl_tramp"]
for a in sys.argv[2:]:
    ov, fn = a.split(":")
    out += ["        PUBLIC  _%s" % fn, "        EXTERN  _%s_ovl" % fn,
            "_%s:" % fn, "        call    ovl_tramp", "        defq    _%s_ovl" % fn]
open(sys.argv[1], "w").write("\n".join(out) + "\n")
