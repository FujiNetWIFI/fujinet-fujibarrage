#!/usr/bin/env python3
"""mkspike.py -- the M0 CPU spike's canned data for p_test.inc (its blasts
and tracks scenes; scenes 3 and 4 are now the shot and the screens).

    mkspike.py OUT.inc

Scene 3, a nuke's fireball: an ellipse at (CX, CY), radii RX x RY, grown in
STEPS rings, each ring the column runs (x, y0, n) that are new at that
size, then the whole ellipse cut to sky. Scene 4, 16 shell tracks: X, Y in
12.12, VX, VY in 12.12 per step, AX, AY in 4.12 (the protocol's OP_ARC
form), each byte big-endian.
"""
import math
import sys

CX, CY, RX, RY, STEPS = 51, 30, 19, 14, 12
FW, FH = 102, 46


def half(rx, ry, dx):
    """rows above/below the centre column dx covers (view.go's inequality)."""
    if rx == 0 or ry == 0:
        return 0 if dx == 0 else -1
    best = -1
    for dy in range(ry + 1):
        if dx * dx * ry * ry + dy * dy * rx * rx <= rx * rx * ry * ry:
            best = dy
    return best


def runs_for(rx, ry, prx, pry):
    out = []
    for dx in range(-rx, rx + 1):
        x = CX + dx
        if not 0 <= x < FW:
            continue
        h = half(rx, ry, dx)
        if h < 0:
            continue
        ph = half(prx, pry, dx) if prx >= 0 else -1
        segs = []
        if ph < 0:
            segs.append((CY - h, CY + h + 1))
        else:
            segs.append((CY - h, CY - ph))
            segs.append((CY + ph + 1, CY + h + 1))
        for a, b in segs:
            a, b = max(a, 0), min(b, FH)
            if b > a:
                out.append((x, a, b - a))
    return out


def main():
    L = ["; GENERATED by tools/chf/mkspike.py -- do not edit."]
    L.append("SPELL:")
    prx = pry = -1
    for k in range(1, STEPS + 1):
        rx, ry = max(1, RX * k // STEPS), max(1, RY * k // STEPS)
        for x, y, n in runs_for(rx, ry, prx, pry):
            L.append("        DB %d,%d,%d" % (x, y, n))
        L.append("        DB 0FEH          ; the ring's end")
        prx, pry = rx, ry
    L.append("        DB 0FFH")
    L.append("SPCRAT:")
    for x, y, n in runs_for(RX, RY, -1, -1):
        L.append("        DB %d,%d,%d" % (x, y, n))
    L.append("        DB 0FFH")
    L.append("SPTRKD:")
    for t in range(16):
        x = 6 + 6 * t
        y = 40
        ang = math.radians(50 + 5 * (t % 8))
        v = 0.9 + 0.05 * (t % 5)
        vx = v * math.cos(ang) * (1 if t % 2 else -1)
        vy = -v * math.sin(ang)
        ay = 0.012
        f = lambda val, bits: int(round(val * (1 << bits)))
        X, Y = f(x, 12) & 0xFFFFFF, f(y, 12) & 0xFFFFFF
        VX, VY = f(vx, 12) & 0xFFFFFF, f(vy, 12) & 0xFFFFFF
        AX, AY = 0, f(ay, 12) & 0xFFFF
        b = []
        for val, n in ((X, 3), (Y, 3), (VX, 3), (VY, 3), (AX, 2), (AY, 2)):
            b += [(val >> (8 * (n - 1 - i))) & 0xFF for i in range(n)]
        L.append("        DB " + ",".join(str(v) for v in b))
    open(sys.argv[1], "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
