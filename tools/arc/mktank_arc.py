#!/usr/bin/env python3
"""mktank_arc.py OUT.inc -- the tanks' sprite pictures by barrel angle, for
p_play.inc: tools/arc/arcmodel.py's tank_pic (what tools/arc/mock_arc.py
draws) for every angle 0-180, consecutive angles with the same picture
grouped.

    TANKI   DB  by angle 0-180: its picture's first row in TANKP (6 x n)
    TANKP   DB  each picture's rows 0-5 (rows 6-7 are the body, $7E)
    TANKX   DB  by field column 0-47: the sprite's X register, the tank's
                middle on the column (arcmodel.put_px - 4 + 43)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arcmodel as A  # noqa: E402


def main(out):
    groups = []
    for a in range(181):
        p = A.tank_pic(a)
        assert p[6] == p[7] == 0x7E
        if groups and groups[-1][1] == p[:6]:
            groups[-1][0] = a
        else:
            groups.append([a, p[:6]])
    idx = []
    for a in range(181):
        idx.append(6 * next(i for i, g in enumerate(groups) if a <= g[0]))
    L = ["; GENERATED by tools/arc/mktank_arc.py -- do not edit.",
         "TANKN   EQU     %d" % len(groups), "TANKI:"]
    for i in range(0, 181, 16):
        L.append("        DB      " + ",".join(str(v) for v in idx[i:i + 16]))
    L.append("TANKP:")
    for g in groups:
        L.append("        DB      " + ",".join("$%02X" % b for b in g[1]))
    L.append("TANKX:")
    for i in range(0, 48, 16):
        L.append("        DB      " + ",".join(str(A.put_px(x) - 4 + 43) for x in range(i, i + 16)))
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
