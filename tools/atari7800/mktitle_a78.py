#!/usr/bin/env python3
"""mktitle_a78.py -- the 7800 title's hills (src/atari7800/title.c): a
column's top line each, 160 of them (the NES's tools/nes/mkgfx_nes.py
title curve, over the 7800's 160 columns), ca65 data in MENURO (bank 2).

    mktitle_a78.py OUT.s
"""
import math
import sys


def main():
    tops = []
    for c in range(160):
        x = c * 256 / 160.0
        h = 128 + 14 * math.sin(x / 37.0) + 9 * math.sin(x / 13.0 + 1.3) - 16 * math.exp(-((x - 128) / 40.0) ** 2)
        tops.append(max(96, min(160, int(round(h)))))
    out = ["; GENERATED by tools/atari7800/mktitle_a78.py: do not edit.",
           '        .segment "MENURO"',
           "        .export _title_hills",
           "_title_hills:"]
    for i in range(0, 160, 16):
        out.append("        .byte   " + ", ".join("%d" % t for t in tops[i:i + 16]))
    open(sys.argv[1], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
