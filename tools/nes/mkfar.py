#!/usr/bin/env python3
"""mkfar.py -- the NES game's far calls (tools/nes/far.txt; the 5200's
tools/atari5200/mkfar.py).

    mkfar.py far.txt OUT.s          the wrappers, in the fixed banks
    mkfar.py far.txt --defs BANK    cc65's -D flags for an overlay of BANK:
                                    its functions renamed ovl_<name>

A wrapper is `jsr far_call` and three bytes: the overlay's bank, its
function's address (src/nes/bank.s's far_call keeps the fastcall argument,
puts the bank in R6, calls it, puts the caller's back and returns its
result): six bytes a function.
"""
import sys


def entries(path):
    out = []
    for line in open(path):
        line = line.split("#")[0].split()
        if line:
            out.append((int(line[0]), line[1]))
    return out


def main():
    ent = entries(sys.argv[1])
    if sys.argv[2] == "--defs":
        b = int(sys.argv[3])
        print(" ".join("-D%s=ovl_%s" % (n, n) for bank, n in ent if bank == b))
        return
    s = ["; GENERATED by tools/nes/mkfar.py from far.txt: do not edit.",
         "        .import far_call",
         ""]
    s += ["        .import _ovl_%s" % n for _, n in ent]
    s += ["        .export _%s" % n for _, n in ent]
    s += ["", "        .code"]
    for b, n in ent:
        s += ["_%s:   jsr     far_call" % n,
              "        .byte   %d" % b,
              "        .addr   _ovl_%s" % n]
    open(sys.argv[2], "w").write("\n".join(s) + "\n")


if __name__ == "__main__":
    main()
