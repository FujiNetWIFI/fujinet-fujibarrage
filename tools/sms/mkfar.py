#!/usr/bin/env python3
"""mkfar.py OUT.asm BANK NAME... -- the stubs for the FAR code's entry points
(src/sms/map.asm's far_tramp): each NAME becomes a resident
`_NAME: call far_tramp; defb BANK; defw _NAME_far`, the FAR file's own copy
of the function compiled as NAME_far (-DNAME=NAME_far, tools/sms/build.mk)."""
import sys

out, bank, names = sys.argv[1], int(sys.argv[2]), sys.argv[3:]
lines = ["; GENERATED by tools/sms/mkfar.py: the FAR code's entry points.",
         "        SECTION code_user",
         "        EXTERN  far_tramp"]
for n in names:
    lines += ["        PUBLIC  _%s" % n, "        EXTERN  _%s_far" % n,
              "_%s:" % n, "        call    far_tramp", "        defb    %d" % bank, "        defw    _%s_far" % n]
open(out, "w").write("\n".join(lines) + "\n")
