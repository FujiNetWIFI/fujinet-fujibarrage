#!/usr/bin/env python3
"""mkfont.py FONT OUT.c -- the Namco 8x8 font (768 bytes, 20h-7Fh, a line a
byte, bit 7 left: gfx/coco/namco.bin) as gen/msdos/font.c's font8[]."""
import sys

data = open(sys.argv[1], "rb").read()
assert len(data) == 768, len(data)
out = ["/* GENERATED by tools/msdos/mkfont.py from %s */" % sys.argv[1],
       "#include <stdint.h>", "const uint8_t font8[768] = {"]
for i in range(0, 768, 16):
    out.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
