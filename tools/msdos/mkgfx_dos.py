#!/usr/bin/env python3
"""mkgfx_dos.py OUT.c -- the PC's field art as C (gen/msdos/gfx.c): the
tanks, the CoCo 3's 12x6 drawings (tools/mkgfx_coco.py) as shape lists for
fld_dots: a count, then (dx, dy) pairs as signed bytes from the tank's foot.

    tk_body tk_dark tk_lite   the CoCo 3's body, treads, highlight
    tk_all                    all three: the CGA's one-colour tank
    tk_flag                   yours: a pennant
    tk_barrel                 19 angles (0, 5 .. 90) of 8 points, no counts
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import mkgfx_coco as mc     # noqa: E402

def arr(name, vals):
    vals = [v & 255 for v in vals]
    lines = ["const uint8_t %s[%d] = {" % (name, len(vals))]
    for i in range(0, len(vals), 16):
        lines.append("    " + ", ".join("%d" % v for v in vals[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)

def main(out):
    all3 = [r.replace("K", "S").replace("H", "S") for r in mc.TANK3]
    bar = mc.barrels(8, 55, 8, -5, -1)
    assert len(bar) == 19 * 16, len(bar)
    parts = [
        ("tk_body", mc.shape(mc.TANK3, "S", -6, -6)),
        ("tk_dark", mc.shape(mc.TANK3, "K", -6, -6)),
        ("tk_lite", mc.shape(mc.TANK3, "H", -6, -6)),
        ("tk_all", mc.shape(all3, "S", -6, -6)),
        ("tk_flag", mc.shape(mc.FLAG3, "W", -6, -10)),
        ("tk_barrel", bar),
    ]
    text = ["/* GENERATED by tools/msdos/mkgfx_dos.py */", "#include <stdint.h>", ""]
    for n, v in parts:
        text.append(arr(n, v))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write("\n".join(text) + "\n")

if __name__ == "__main__":
    main(sys.argv[1])
