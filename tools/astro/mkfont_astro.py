#!/usr/bin/env python3
"""mkfont_astro.py gfx/font3x5.txt OUT.inc -- the 3x5 font for the
Astrocade's magic expander: FONT35, 64 glyphs (20H-5FH) of 5 bytes, top row
first, ink in the HIGH nibble with bit 7 the leftmost pixel (the fourth
pixel the gap), as font46.inc's; characters missing from the master are
blank. (tools/mkfont35.py reads the same master for the Atari.)"""
import sys

glyphs, cur = {}, None
for line in open(sys.argv[1]):
    line = line.rstrip("\n")
    if line.startswith("# "):
        continue
    if line.startswith("char "):
        cur = line[5:6]
        glyphs[cur] = []
        continue
    if cur is not None and len(line) == 3 and len(glyphs[cur]) < 5:
        glyphs[cur].append(sum(0x80 >> i for i in range(3) if line[i] == "#"))
out = ["; GENERATED by tools/astro/mkfont_astro.py from gfx/font3x5.txt -- do not edit.",
       "; 64 glyphs (20H-5FH), 5 bytes each, ink in the high nibble (bit 7 leftmost).",
       "FONT35:"]
for c in range(32, 96):
    g = glyphs.get(chr(c), [0] * 5)
    out.append("        DB      %s    ; %02XH" % (",".join("0%02XH" % v for v in g), c))
open(sys.argv[2], "w").write("\n".join(out) + "\n")
