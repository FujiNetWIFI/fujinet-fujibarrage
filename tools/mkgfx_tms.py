#!/usr/bin/env python3
"""mkgfx_tms.py -- the TMS9918's art for the Adam (and the MSX to come),
written as z80asm data.

    mkgfx_tms.py font OUT.asm      the Namco 8x8 font (gfx/coco/namco.bin),
                                   ' ' to '_' (64 glyphs, 8 bytes each): _font8
    mkgfx_tms.py art OUT.bin       the art block (src/adam/chain.asm's
                                   art_load): the VRAM's 3800h-3BFFh, the tank
                                   sprites (19 barrel angles 0, 10 .. 180, then
                                   the same with your pennant; 8x8, the foot at
                                   the bottom, the turret's top at column 3,
                                   row 3), "ART!" at 508, the font at 512
    mkgfx_tms.py field OUT.asm     the stars (_st_starb: 256 bytes, a few
                                   with a pixel lit)
    mkgfx_tms.py title OUT.asm [PREVIEW.png]   the menu's title picture: a
                                   sunset over the hills, two tanks, a shell's
                                   arc and its burst, FUJIBARRAGE (the CoCo's,
                                   tools/mktitle_coco.py, drawn again in the
                                   TMS9918's colours), two colours an 8-pixel
                                   run; its pattern and colour tables packed
                                   (src/tms9918/lzd.asm unpacks): _title_pat,
                                   _title_col
"""
import math
import random
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")


def rows(data, per=16):
    out = []
    for i in range(0, len(data), per):
        out.append("        defb    " + ", ".join("$%02X" % b for b in data[i:i + per]))
    return out


def emit(path, lines):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        f.write("; GENERATED by tools/mkgfx_tms.py: do not edit.\n")
        f.write("\n".join(lines) + "\n")


def font(path):
    f = open(os.path.join(ROOT, "gfx", "coco", "namco.bin"), "rb").read()
    glyphs = f[0:64 * 8]                # ' ' (32) to '_' (95)
    emit(path, ["        SECTION rodata_user", "        PUBLIC  _font8", "_font8:"] + rows(glyphs))


# the tank: its body 7 by 5 over its foot (rows 3-7 of the sprite), the
# barrel 3 pixels from the turret's top (column 3, row 3) at its angle
BODY = [
    "..SSS...",
    ".SSSSS..",
    "SSSSSSS.",
    "SSSSSSS.",
    "S.S.S.S.",
]
PAR = 73                        # the TMS9918's pixel, 64ths (src/platform-specific/field.h)


def tank(angle, pennant):
    px = [[0] * 8 for _ in range(8)]
    for j, row in enumerate(BODY):
        for i, c in enumerate(row):
            if c == "S":
                px[3 + j][i] = 1
    r = math.radians(angle)
    for k in range(1, 4):
        x = 3 + int(math.floor(k * math.cos(r) + 0.5))
        y = 3 - int(math.floor(k * math.sin(r) * 64 / PAR + 0.5))
        if 0 <= x < 8 and 0 <= y < 8:
            px[y][x] = 1
    if pennant:                 # on the side away from the barrel
        fx = 0 if angle <= 90 else 6
        for (dx, dy) in ((0, 0), (1, 0), (0, 1), (0, 2)):
            px[dy][fx + dx] = 1
    return [sum(px[y][x] << (7 - x) for x in range(8)) for y in range(8)]


def sprites():
    spr = []
    for pennant in (0, 1):
        for a in range(0, 181, 10):
            spr += tank(a, pennant)
    return spr


def art(path):
    spr = sprites()
    b = bytearray(1024)
    b[0:len(spr)] = bytes(spr)
    assert len(spr) <= 508
    b[508:512] = b"ART!"
    b[512:1024] = open(os.path.join(ROOT, "gfx", "coco", "namco.bin"), "rb").read()[0:512]
    open(path, "wb").write(b)


def field(path):
    rnd = random.Random(1987)
    stars = [0] * 256
    for i in range(256):
        if rnd.random() < 0.09:
            stars[i] = 0x80 >> rnd.randrange(8)
    lines = ["        SECTION rodata_user", "        PUBLIC  _st_starb",
             "_st_starb:"] + rows(stars)
    emit(path, lines)


# the TMS9918's colours (as adamcore shows them, near enough)
TMS = [(0, 0, 0), (0, 0, 0), (33, 200, 66), (94, 220, 120), (84, 85, 237), (125, 118, 252),
       (212, 82, 77), (66, 235, 245), (252, 85, 84), (255, 121, 120), (212, 193, 84),
       (230, 206, 128), (33, 176, 59), (201, 91, 186), (204, 204, 204), (255, 255, 255)]
(BLACK, MGREEN, LGREEN, DBLUE, LBLUE, DRED, CYAN, MRED, LRED, DYELLOW, LYELLOW, DGREEN,
 MAGENTA, GREY, WHITE) = range(1, 16)


def title_canvas():
    sys.path.insert(0, HERE)
    import mktitle_coco as mt
    W, H = 256, 192
    cv = mt.Canvas(W, H, DBLUE)
    f = mt.font3()
    b3 = lambda ch: mt.glyph_bits3(f, ch)
    # the sky: night to dusk to fire, in bands
    bands = [(DBLUE, MAGENTA, 0, 48), (MAGENTA, MRED, 48, 90), (MRED, LRED, 90, 120), (LRED, DYELLOW, 120, 144)]
    for a, b, y0, y1 in bands:
        for y in range(y0, y1):
            cv.rect(0, y, W, y + 1, a if (y - y0) * 2 < (y1 - y0) else b)   # (bands: no dither)
    rnd = random.Random(7)
    for _ in range(32):
        x, y = rnd.randrange(W), rnd.randrange(44)
        cv.set(x, y, WHITE if rnd.random() < 0.3 else GREY)
    # the sun, banded
    sx, sy, sr = 172, 144, 30
    for y in range(sy - sr, sy):
        if (sy - y) % 7 == 1 and y > sy - 20:
            continue
        for x in range(sx - 40, sx + 41):
            if ((x - sx) * PAR / 64) ** 2 + (y - sy) ** 2 <= sr * sr:
                cv.set(x, y, LYELLOW if y < sy - 12 else DYELLOW)
    far = mt.hills(W, 134, 12, 0.039, 0.096, 1.3)
    for x in range(W):
        for y in range(far[x], H):
            cv.set(x, y, DRED)
    near = mt.hills(W, 154, 10, 0.025, 0.062, 0.4)
    for x in range(W):
        for y in range(near[x], H):
            d = y - near[x]
            if d < 2:
                c = MGREEN
            else:
                c = DGREEN if y > 166 else MGREEN
                if (y // 6) % 3 == 0 and d > 6:
                    c = DRED
            cv.set(x, y, c)
    rows = ["....SSSS....", "...SSHHSS...", ".SSSSSSSSSS.", "SSSSSSSSSSSS", "KSKSKSKSKSKS", ".KKKKKKKKKK."]
    lx, rx = 50, 210
    mt.tank(cv, lx, near[lx] + 1, rows, {"S": MRED, "K": BLACK, "H": WHITE}, 2, 2, 52, PAR, 9, 2, MRED)
    mt.tank(cv, rx, near[rx] + 1, rows, {"S": LBLUE, "K": BLACK, "H": WHITE}, 2, 2, 150, PAR, 9, 2, LBLUE)
    pts = mt.arc(lx + 10, near[lx] - 18, rx - 28, near[rx - 28] - 2, 80, 50)
    for k, (x, y) in enumerate(pts[:-3]):
        if k % 2 == 0:
            cv.set(int(x), int(y), WHITE)
            cv.set(int(x) + 1, int(y), LYELLOW)
    bx, by = int(pts[-1][0]), int(pts[-1][1])
    mt.burst(cv, bx, by, 11, PAR, [(0.3, WHITE), (0.55, LYELLOW), (0.75, DYELLOW), (1.01, LRED)])
    s = "FUJIBARRAGE"
    wl = len(s) * 8 * 2 + 0
    grad = [WHITE, LYELLOW, LYELLOW, LYELLOW, DYELLOW, DYELLOW, DYELLOW, LRED, LRED, MRED, MRED, DRED, DRED]
    mt.logo(cv, b3, s, (W - wl) // 2 - 2, 10, 2, 3, 8,
            lambda x, y: grad[min(len(grad) - 1, y * len(grad) // 24)], BLACK, DBLUE)
    tag = "AIM, FIRE, TALK TRASH."
    tw = len(tag) * 8
    mt.text(cv, b3, tag, (W - tw) // 2 + 1, 43, BLACK)
    mt.text(cv, b3, tag, (W - tw) // 2, 42, WHITE)
    pf = "PRESS FIRE"
    pw = len(pf) * 8
    cv.rect((W - pw) // 2 - 4, 176, (W + pw) // 2 + 4, 188, BLACK)
    mt.text(cv, b3, pf, (W - pw) // 2, 178, LYELLOW)
    return cv


def dist(a, b):
    return sum((x - y) ** 2 for x, y in zip(TMS[a], TMS[b]))


def tables(cv):
    """the pattern and colour tables: two colours an 8-pixel run (the two
    commonest; any other becomes the nearer of them)"""
    pat, col = bytearray(6144), bytearray(6144)
    for y in range(192):
        for cx in range(32):
            run = [cv.px[y][cx * 8 + i] for i in range(8)]
            counts = sorted(set(run), key=lambda c: -run.count(c))
            a = counts[0]
            b = counts[1] if len(counts) > 1 else a
            if len(counts) > 2:             # a highlight (the arc, a star) over a dither keeps its colour
                hi = [c for c in counts[1:] if c in (WHITE, LYELLOW)]
                if hi and a not in (WHITE, LYELLOW):
                    b = hi[0]
            bits = 0
            for i, c in enumerate(run):
                if c != a and (c == b or dist(c, b) < dist(c, a)):
                    bits |= 0x80 >> i
            at = (y >> 3) * 256 + cx * 8 + (y & 7)
            pat[at] = bits
            col[at] = b << 4 | a
    return pat, col


def title(path, preview=None):
    sys.path.insert(0, HERE)
    import mktitle_coco as mt
    cv = title_canvas()
    pat, col = tables(cv)
    for stream in (pat, col):
        assert mt.lz_unpack(mt.lz_pack(stream)) == bytes(stream)
    lines = ["        SECTION rodata_user", "        PUBLIC  _title_pat, _title_col", "_title_pat:"] + \
        rows(mt.lz_pack(pat)) + ["_title_col:"] + rows(mt.lz_pack(col))
    emit(path, lines)
    if preview:
        from PIL import Image
        im = Image.new("RGB", (256, 192))
        for y in range(192):
            for x in range(256):
                at = (y >> 3) * 256 + (x >> 3) * 8 + (y & 7)
                c = col[at] >> 4 if pat[at] & (0x80 >> (x & 7)) else col[at] & 15
                im.putpixel((x, y), TMS[c])
        im.resize((768, 576), Image.NEAREST).save(preview)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    what, out = sys.argv[1], sys.argv[2]
    if what == "font":
        font(out)
    elif what == "field":
        field(out)
    elif what == "art":
        art(out)
    elif what == "title":
        title(out, sys.argv[3] if len(sys.argv) > 3 else None)
    else:
        sys.exit("mkgfx_tms.py: what is %s?" % what)


if __name__ == "__main__":
    main()
