#!/usr/bin/env python3
"""mktank_s2.py -- the Studio II's tanks: each seat's mark, the barrel at
each 15-degree step and the hull, as 16-row images for the cart's sprites
(MASK mode: an image and its mask, the mask a one-dot halo), and the marks
as app glyphs for the text (the HUD, the rooms).

    mktank_s2.py OUT.inc [--sheet PNG]

A tank's image is 8 dots wide, 16 lines (top to bottom):
    0       blank (the mask's halo above the mark)
    1-6     the seat's mark (3x3, each row twice), over the hull's centre
    7       blank
    8-11    the barrel (from the turret's top, out 1.5 dots, up 4 lines)
    12-15   the hull, 3 dots: the turret (inset), then three rows
The hull's bottom centre is the tank's (x, y): the sprite goes at
(x - 3, y - 16). Rows are bytes, bit 7 the leftmost dot.

Emits (AS, CPU 1802): TKMARK (10 x 16), TKBAR (13 x 16), TKHULL (16): the
image rows, each part's rows zero elsewhere, so an image is their OR; the
same with M for the masks (each part's halo, so a mask is their OR too);
MARKGLY (10 x 12): the glyph rows (bit 3 the leftmost of four).
"""
import math
import sys

W, H = 8, 16
CX = 3                      # the hull's centre dot

# the seats' marks, 3x3 (row strings, '#' a dot): all different at a glance
MARKS = [
    ("###", "###", "###"),  # 0 block
    ("###", "#.#", "###"),  # 1 ring
    (".#.", "###", "###"),  # 2 peak
    ("###", "###", ".#."),  # 3 drop
    (".#.", "###", ".#."),  # 4 cross
    ("#.#", ".#.", "#.#"),  # 5 saltire
    ("###", "...", "###"),  # 6 bars
    ("#.#", "#.#", "#.#"),  # 7 posts
    (".#.", "#.#", ".#."),  # 8 diamond
    ("#..", "##.", "###"),  # 9 wedge
]
HULL = (".#.", "###", "###", "###")


def rows_of(pattern, top, dbl):
    """a 3-wide pattern at the hull's columns from row top (each row twice
    if dbl) as 16 row bytes"""
    out = [0] * H
    r = top
    for p in pattern:
        b = 0
        for i, ch in enumerate(p):
            if ch == "#":
                b |= 0x80 >> (CX - 1 + i)
        for _ in range(2 if dbl else 1):
            out[r] = b
            r += 1
    return out


def barrel(step):
    """the barrel at angle 15 step: dots on the segment from the turret's
    top centre (3.5, 12) out 1.5 dots and up 4 lines, sampled finely"""
    a = math.radians(15 * step)
    out = [0] * H
    x0, y0 = CX + 0.5, 12.0
    x1, y1 = x0 + 1.6 * math.cos(a), y0 - 4.2 * math.sin(a)
    for k in range(1, 41):
        t = k / 40
        x, y = x0 + (x1 - x0) * t, y0 - (y0 - y1) * t
        xi, yi = int(math.floor(x)), int(math.floor(y))
        if yi >= 12:            # (level: in the turret's row, beside it)
            yi = 12
            if xi == CX:
                continue
        if 0 <= xi < W and 8 <= yi <= 12:
            out[yi] |= 0x80 >> xi
    return out


def halo(rows):
    """a mask: the dots and every dot next to one (8 ways), within the image"""
    out = [0] * H
    for r in range(H):
        for dr in (-1, 0, 1):
            q = r + dr
            if 0 <= q < H:
                b = rows[q]
                out[r] |= b | ((b << 1) & 0xFF) | (b >> 1)
    return out


def glyph(pattern):
    """the mark as a 4x12 glyph (bit 3 the leftmost): rows 2-3, 4-6, 7-8;
    the short font's rows (1, 3, 5, 7, 9) catch each once"""
    rr = []
    for p in pattern:
        b = 0
        for i, ch in enumerate(p):
            if ch == "#":
                b |= 8 >> i
        rr.append(b)
    return [0, 0, rr[0], rr[0], rr[1], rr[1], rr[1], rr[2], rr[2], 0, 0, 0]


def db(rows):
    return "        DB      " + ", ".join("%03XH" % b for b in rows)


def main():
    out = sys.argv[1]
    marks = [rows_of(m, 1, True) for m in MARKS]
    hull = rows_of(HULL, 12, False)
    bars = [barrel(s) for s in range(13)]
    for b in bars:                      # (the turret's row: the hull's own)
        b[12] &= ~hull[12] & 0xFF
    lines = ["; GENERATED by tools/s2/mktank_s2.py -- do not edit.",
             "TK_H    EQU     %d" % H, "TK_CX   EQU     %d" % CX,
             "        PFIT    16*10", "TKMARK:"]
    lines += [db(m) for m in marks]
    lines += ["        PFIT    16*10", "TKMARKM:"] + [db(halo(m)) for m in marks]
    lines += ["        PFIT    16*13", "TKBAR:"] + [db(b) for b in bars]
    lines += ["        PFIT    16*13", "TKBARM:"] + [db(halo(b)) for b in bars]
    lines += ["        PFIT    32", "TKHULL:", db(hull), "TKHULLM:", db(halo(hull))]
    lines += ["        PFIT    12*10", "MARKGLY:"] + [db(glyph(m)) for m in MARKS]
    open(out, "w").write("\n".join(lines) + "\n")
    if "--sheet" in sys.argv:
        sheet(sys.argv[sys.argv.index("--sheet") + 1], marks, hull, bars)


def sheet(path, marks, hull, bars):
    """every seat's tank at 0, 45, 90, 135, 180 degrees, on sky and in dirt,
    at a TV's aspect (a dot 10 wide, a line 3 tall)"""
    from PIL import Image
    cw, ch = 10 * 10, 3 * 20
    im = Image.new("L", (cw * 10, ch * 10), 0)
    px = im.load()
    for s in range(10):
        for j, step in enumerate((0, 3, 6, 9, 12)):
            for dirt in (0, 1):
                rows = [m | b | h for m, b, h in zip(marks[s], bars[step], hull)]
                mask = [a | b | c for a, b, c in zip(halo(marks[s]), halo(bars[step]), halo(hull))]
                ox, oy = s * cw, (j * 2 + dirt) * ch
                for y in range(20):
                    for x in range(10):
                        bg = 255 if dirt and y >= 8 else 0
                        v = bg
                        ix, iy = x - 1, y - 2
                        if 0 <= ix < W and 0 <= iy < H:
                            if (mask[iy] >> (7 - ix)) & 1:
                                v = 0
                            if (rows[iy] >> (7 - ix)) & 1:
                                v = 255
                        for dx in range(10):
                            for dy in range(3):
                                px[ox + x * 10 + dx, oy + y * 3 + dy] = v
    im.save(path)


if __name__ == "__main__":
    main()
