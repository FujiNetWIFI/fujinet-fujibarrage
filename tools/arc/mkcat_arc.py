#!/usr/bin/env python3
"""mkcat_arc.py CATALOG.bin CAT.inc CATEQU.inc [CATSET.inc CATITEM.inc] -- the server's CATALOG
(barraged -catalog) as the Arcadia's CAT page keeps it: its cart RAM has no
room for the 1612 bytes the server sends, so they live in ROM (the
Astrocade's tools/astro/mkcat_astro.py, for AS 2650), and the link drops
the K frames. The STATE's OFF_CAT_LEN and OFF_CAT_SUM are checked against
CATLEN, CATS1, CATS2 (p_room.inc CATOURS): a server whose catalog differs
gets "UPDATE BARRAGE".

    CAT.inc     CATRAW   the catalog's bytes as the server sends them
                CIDX     DWBE each item's record (kind, arms, bundle,
                         price24, name: a length, then ASCII)
                CSIDX    DWBE each setting's (page, type, label, then a
                         choice's names or a number's min16 step16 count dec)
                CPIDX    DWBE each page's name   CTIDX  DWBE each tier's name
    CATEQU.inc  CATLEN CATS1 CATS2 CNITEMS CNSETS CNPAGES CNTIERS: every
                page's assembly sees them
    CATSET.inc  (M4) the waiting room's: the settings digested, their names
                as glyph strings ($FF ends each): CSREC 8 bytes a setting
                (page, type, count, decimals, min16 LE, step16 LE), CSLAB
                DWBE its label, CSCH DWBE its first choice's name (the rest
                follow; 0 for a number), CPNAM DWBE a page's name; beside
                it cattier.inc: CTN6 the tiers' names in 6 cells each
    CATITEM.inc (M4) the shop's: CIARM, CIBUN, CIPRL, CIPRH (an item's
                arms level, bundle, price's low and high byte)

The names stay ASCII with their lengths (cat.c's layout): M4's accessors
turn them into glyphs as they draw (A2G; '-' ':' '/' are the text screens'
user glyphs, '%' has none yet).
"""
import os
import sys


def main(src, out, equ, setout=None, itemout=None):
    cat = open(src, "rb").read()
    s1 = s2 = 0
    for b in cat:
        s1 = (s1 + b) % 255
        s2 = (s2 + s1) % 255
    nitems, nsets, npages = cat[1], cat[2], cat[3]
    odd = set()

    def lstr(at):
        n = cat[at]
        for c in cat[at + 1:at + 1 + n].decode("ascii"):
            if not (c.isupper() or c.isdigit() or c in " .,+$-:/"):
                odd.add(c)
        return at + 1 + n

    at = 4
    pages = []
    for p in range(npages):
        pages.append(at)
        at = lstr(at)
    items = []
    for i in range(nitems):
        items.append(at)
        at = lstr(at + 6)
    sets = []
    for k in range(nsets):
        sets.append(at)
        typ = cat[at + 1]
        at = lstr(at + 2)
        if typ == 0:
            n = cat[at]
            at += 1
            for j in range(n):
                at = lstr(at)
        else:
            at += 6
    ntiers = cat[at]
    at += 1
    tiers = []
    for t in range(ntiers):
        tiers.append(at)
        at = lstr(at)
    assert at == len(cat), (at, len(cat))

    L = ["; GENERATED by tools/arc/mkcat_arc.py from the server's CATALOG -- do not edit.",
         "CATRAW:"]
    for i in range(0, len(cat), 16):
        L.append("        DB      " + ",".join("$%02X" % b for b in cat[i:i + 16]))
    for name, offs in (("CIDX", items), ("CSIDX", sets), ("CPIDX", pages), ("CTIDX", tiers)):
        L.append(name + ":")
        for o in offs:
            L.append("        DWBE    CATRAW+%d" % o)
    open(out, "w").write("\n".join(L) + "\n")
    E = ["; GENERATED by tools/arc/mkcat_arc.py -- do not edit.",
         "CATLEN  EQU     %d" % len(cat), "CATS1   EQU     %d" % s1, "CATS2   EQU     %d" % s2,
         "CNITEMS EQU     %d" % nitems, "CNSETS  EQU     %d" % nsets, "CNPAGES EQU     %d" % npages,
         "CNTIERS EQU     %d" % ntiers]
    open(equ, "w").write("\n".join(E) + "\n")
    if setout:
        sets_out(cat, pages, sets, tiers, setout)
    if itemout:
        items_out(cat, items, itemout)


GLY = {" ": 0, ".": 0x34, ",": 0x35, "+": 0x36, "$": 0x37, "%": 0x38, "<": 0x39, "!": 0x3A,
       "?": 0x3B, ">": 0x3C, "-": 0x3D, ":": 0x3E, "/": 0x3F}


def glyphs(t):
    """ASCII to the text screens' glyph codes (macros.inc GLYPHS)"""
    out = []
    for c in t.upper():
        if c.isdigit():
            out.append(0x10 + ord(c) - 48)
        elif "A" <= c <= "Z":
            out.append(0x1A + ord(c) - 65)
        elif c in GLY:
            out.append(GLY[c])
        else:
            sys.exit("mkcat_arc: no glyph for %r in %r" % (c, t))
    return out


def gstr(t):
    return "        DB      " + ",".join("$%02X" % g for g in glyphs(t) + [0xFF])


def lstr_at(cat, at):
    n = cat[at]
    return cat[at + 1:at + 1 + n].decode("ascii"), at + 1 + n


def sets_out(cat, pages, sets, tiers, out):
    L = ["; GENERATED by tools/arc/mkcat_arc.py from the server's CATALOG -- do not edit.",
         "; The settings for the waiting room (p_room.inc), as glyph strings.", "CSREC:"]
    labs, chs = [], []
    for k, at in enumerate(sets):
        pg, typ = cat[at], cat[at + 1]
        lab, at = lstr_at(cat, at + 2)
        labs.append(lab)
        if typ == 0:
            n = cat[at]
            at += 1
            names = []
            for j in range(n):
                c, at = lstr_at(cat, at)
                names.append(c)
            chs.append(names)
            L.append("        DB      %d,%d,%d,0,0,0,0,0     ; %s" % (pg, typ, n, lab))
        else:
            mn, st, cnt, dec = cat[at] | cat[at + 1] << 8, cat[at + 2] | cat[at + 3] << 8, cat[at + 4], cat[at + 5]
            chs.append(None)
            L.append("        DB      %d,%d,%d,%d,%d,%d,%d,%d     ; %s" % (
                pg, typ, cnt, dec, mn & 255, mn >> 8, st & 255, st >> 8, lab))
    L.append("CSLAB:")
    L += ["        DWBE    CSL%d" % k for k in range(len(sets))]
    L.append("CSCH:")
    L += ["        DWBE    %s" % ("CSC%d" % k if chs[k] else "0") for k in range(len(sets))]
    L.append("CPNAM:")
    L += ["        DWBE    CPN%d" % p for p in range(len(pages))]
    for k, lab in enumerate(labs):
        L.append("CSL%d:" % k)
        L.append(gstr(lab))
        if chs[k]:
            L.append("CSC%d:" % k)
            L += [gstr(c) for c in chs[k]]
    for p, at in enumerate(pages):
        L.append("CPN%d:" % p)
        L.append(gstr(lstr_at(cat, at)[0]))
    open(out, "w").write("\n".join(L) + "\n")
    T = ["; GENERATED by tools/arc/mkcat_arc.py from the server's CATALOG -- do not edit.",
         "; The bots' tiers, 6 cells each (the waiting room's seats).", "CTN6:"]
    for at in tiers:
        t = lstr_at(cat, at)[0][:6].ljust(6)
        T.append("        DB      " + ",".join("$%02X" % g for g in glyphs(t)) + "     ; " + t)
    open(os.path.join(os.path.dirname(out), "cattier.inc"), "w").write("\n".join(T) + "\n")


def items_out(cat, items, out):
    L = ["; GENERATED by tools/arc/mkcat_arc.py from the server's CATALOG -- do not edit.",
         "; The items for the shop (p_shop.inc): arms level, bundle, price (16-bit)."]
    rows = []
    for at in items:
        price = cat[at + 3] | cat[at + 4] << 8 | cat[at + 5] << 16
        if price > 65535:
            sys.exit("mkcat_arc: a price past 16 bits (%d): the shop's CIPRH would lose it" % price)
        rows.append((cat[at + 1], cat[at + 2], price & 255, price >> 8))
    for name, i in (("CIARM", 0), ("CIBUN", 1), ("CIPRL", 2), ("CIPRH", 3)):
        L.append(name + ":")
        for j in range(0, len(rows), 16):
            L.append("        DB      " + ",".join("%d" % r[i] for r in rows[j:j + 16]))
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:6])
