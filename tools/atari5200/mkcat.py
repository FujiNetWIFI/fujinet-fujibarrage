#!/usr/bin/env python3
"""mkcat.py -- the server's CATALOG in ROM, for a client with no RAM for it
(the 5200: src/cat.c's CAT_ROM). `barraged -catalog` writes its bytes;
this writes them as ca65 data, indexed as cat_check() would index them in
RAM, and a header with their length and Fletcher-16 (the STATE's
OFF_CAT_LEN and OFF_CAT_SUM say whether the server's is the same one).

    mkcat.py CATALOG.bin PROTO.h OUT.s OUT.h
"""
import re
import sys


def main():
    cat = open(sys.argv[1], "rb").read()
    proto = open(sys.argv[2]).read()
    n_ = lambda k: int(re.search(r"#define %s\s+(\d+)" % k, proto).group(1))
    n_items, n_settings, n_tiers = n_("N_ITEMS"), n_("N_SETTINGS"), n_("N_TIERS")
    skip = lambda at: at + 1 + cat[at]
    page_at, item_at, set_at, tier_at = [], [], [], []
    at = 4
    for _ in range(min(cat[3], 4)):
        page_at.append(at)
        at = skip(at)
    page_at += [0] * (4 - len(page_at))         # (as cat_check leaves them)
    for _ in range(n_items):
        item_at.append(at)
        at = skip(at + 6)
    for _ in range(n_settings):
        set_at.append(at)
        if cat[at + 1] == 0:                # a choice: label, n, names
            at = skip(at + 2)
            n = cat[at]
            at += 1
            for _ in range(n):
                at = skip(at)
        else:                               # a number: label, then 6 bytes
            at = skip(at + 2) + 6
    n = cat[at]
    at += 1
    for _ in range(min(n, n_tiers)):
        tier_at.append(at)
        at = skip(at)
    tier_at += [0] * (n_tiers - len(tier_at))
    if at > len(cat):
        sys.exit("mkcat: the catalog ends short (%d of %d)" % (len(cat), at))
    s1 = s2 = 0
    for c in cat:
        s1 = (s1 + c) % 255
        s2 = (s2 + s1) % 255
    out = ["; GENERATED by tools/atari5200/mkcat.py from barraged -catalog: do not edit.",
           "        .export _catalog, _item_at, _set_at, _page_at, _tier_at",
           '        .segment "CATALOG"']
    def rows(name, data, w):
        out.append(name + ":")
        for i in range(0, len(data), 16):
            out.append("        .%s   %s" % ("byte" if w == 1 else "word",
                                            ", ".join("$%0*X" % (2 * w, v) for v in data[i:i + 16])))
    rows("_catalog", list(cat), 1)
    rows("_item_at", item_at, 2)
    rows("_set_at", set_at, 2)
    rows("_page_at", page_at, 2)
    rows("_tier_at", tier_at, 2)
    open(sys.argv[3], "w").write("\n".join(out) + "\n")
    open(sys.argv[4], "w").write("/* GENERATED by tools/atari5200/mkcat.py: do not edit. */\n"
                                 "#define CAT_LEN %d\n#define CAT_S1 %d\n#define CAT_S2 %d\n" % (len(cat), s1, s2))
    print("mkcat: %d bytes, sum %02X %02X" % (len(cat), s1, s2))


if __name__ == "__main__":
    main()
