#!/usr/bin/env python3
"""mksfx_a2.py -- the effects for the Mockingboard's AY-3-8910
(src/apple2/mock.s), from the Intellivision's (src/intv/sfx.asm: designed
for the same family of PSG, and heard and approved). The AY here is
clocked at the Apple's 1020484 Hz, the Intellivision's at 1789773 Hz: every
period (a tone's, the noise's, the envelope's) is scaled by their ratio, so
each effect is the same pitch and the same length.

A step here: jiffies (0 ends the effect), then the volume (bits 0-3) with
bit 4 noise (the tone off) and bit 5 the envelope (its decay restarted),
then the period (a tone's, 12 bits; the noise's, 5), low byte first; with
the envelope, its period after, low byte first. The cue tables are .addr
pairs (the body, the low end; 0 none).

usage: mksfx_a2.py src/intv/sfx.asm OUT.s
"""
import re
import sys

RATIO = 1020484.0 / 1789773.0
SX_N, SX_E = 0x1000, 0x2000


def value(tok):
    tok = tok.strip()
    tok = tok.replace("SX_N", str(SX_N)).replace("SX_E", str(SX_E))
    tok = re.sub(r"\$([0-9A-Fa-f]+)", lambda m: str(int(m.group(1), 16)), tok)
    return eval(tok, {"__builtins__": {}}, {})


def tables(src):
    """label -> its DECLE words (as tokens), continuation lines included"""
    out, cur = {}, None
    for line in open(src):
        line = line.split(";")[0].rstrip()
        m = re.match(r"^(\w+):\s*DECLE\s+(.*)$", line)
        if m:
            cur = m.group(1)
            out[cur] = [t for t in m.group(2).split(",") if t.strip()]
            continue
        m = re.match(r"^\s+DECLE\s+(.*)$", line)
        if m and cur:
            out[cur] += [t for t in m.group(1).split(",") if t.strip()]
            continue
        if re.match(r"^\S", line):
            cur = None
    return out


def scale(p, lo, hi):
    return max(lo, min(hi, round(p * RATIO)))


def effect(words):
    vals = [value(t) for t in words]
    out, i = [], 0
    while True:
        what, how = vals[i], vals[i + 1]
        i += 2
        if how == 0:
            out.append(0)
            return out
        jif, vol = (how >> 4) & 255, how & 15
        flags = 0
        if what & SX_N:
            flags |= 0x10
            per = scale(what & 31, 1, 31)
        else:
            per = scale(what & 0x0FFF, 1, 4095)
        if what & SX_E:
            flags |= 0x20
        out += [jif, vol | flags, per & 255, per >> 8]
        if what & SX_E:
            ep = scale(vals[i], 1, 65535)
            i += 1
            out += [ep & 255, ep >> 8]


def main():
    src, dst = sys.argv[1:3]
    t = tables(src)
    fx = [n for n in t if n.startswith("sx_") and n not in ("sx_cues", "sx_booms", "sx_ui")]
    lines = ["; GENERATED by tools/mksfx_a2.py from %s: edit that, not this." % src,
             "; (A step: jiffies, 0 the end; the volume | $10 noise | $20 the envelope;",
             "; the period, low first; with the envelope its period after.)",
             "        .export sx_cues, sx_booms, sx_ui",
             "        .rodata"]
    n = 0
    for name in fx:
        b = effect(t[name])
        n += len(b)
        lines.append("%s:%s.byte   %s" % (name, " " * max(1, 10 - len(name)), ", ".join(str(x) for x in b)))
    for tab in ("sx_cues", "sx_booms", "sx_ui"):
        words = [w.strip() for w in t[tab]]
        n += 2 * len(words)
        lines.append("%s:" % tab)
        for k in range(0, len(words), 2):
            pair = words[k:k + 2]
            lines.append("        .addr   %s" % ", ".join(pair))
    open(dst, "w").write("\n".join(lines) + "\n")
    print("%s: %d effects, %d bytes" % (dst, len(fx), n))


if __name__ == "__main__":
    main()
