#!/usr/bin/env python3
"""mktab_intv.py OUT.asm -- the Intellivision field's lookup tables
(src/intv/fld.asm, cell.asm) as CP1610 DECLEs: each row's offset in a plane
and its first cell, a pixel's bit, a span's end masks, a column's two bits
spread over a word, a column image's row masks, the quarter circle the
ellipses are drawn from (fld.s's q32), and each byte's count of set bits."""
import sys

FIELD_H = 80


def table(f, label, vals, per=8):
    f.write("%s:\n" % label)
    for i in range(0, len(vals), per):
        f.write("        DECLE   %s\n" % ", ".join("$%04X" % (v & 0xFFFF) for v in vals[i:i + per]))


def main():
    bit = [0x80 >> k for k in range(8)]
    with open(sys.argv[1], "w") as f:
        f.write(";; GENERATED by tools/mktab_intv.py: edit that, not this.\n")
        # a row's first word in a plane (cell column 0) and its first cell
        table(f, "fld_yofs", [(y >> 3) * 80 + ((y >> 1) & 3) for y in range(FIELD_H)])
        table(f, "fld_ycell", [(y >> 3) * 20 for y in range(FIELD_H)])
        table(f, "fld_bit", bit)
        table(f, "fld_lmask", [0xFF >> k for k in range(8)])                 # pixels k-7
        table(f, "fld_rmask", [(0xFF00 >> (k + 1)) & 0xFF for k in range(8)])  # pixels 0-k
        # a column (pixel k of its cell) given rows 2i, 2i+1 as bits 0, 1: that word's bits
        table(f, "fld_exp", [(bit[k] if b & 1 else 0) | (bit[k] << 8 if b & 2 else 0)
                             for k in range(8) for b in range(4)])
        # a column image's byte (bit r: the cell's row r): rows lo-7, rows 0-(hi-1)
        table(f, "fld_from", [(0xFF << lo) & 0xFF for lo in range(9)])
        table(f, "fld_to", [(1 << hi) - 1 for hi in range(9)])
        # fld.s's quarter circle: q32[i] = 64 sqrt(1 - (i/32)^2)
        table(f, "fld_q32", [64, 64, 64, 63, 63, 62, 62, 61, 60, 59, 57, 56, 54, 53, 51, 49,
                             46, 44, 41, 38, 35, 32, 28, 24, 20, 15, 10, 5, 0, 0, 0, 0, 0])
        table(f, "fld_pop", [bin(b).count("1") for b in range(256)], 16)


if __name__ == "__main__":
    main()
