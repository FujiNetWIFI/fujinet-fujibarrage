W, H, XPOS = 192, 262, 32


def put_px(x):
    """a field column's left pixel (blocks 3, 3, 2 wide)"""
    return 8 * (x // 3) + (0, 3, 6)[x % 3]


def tank_pic(angle):
    """a tank's 8x8 sprite: a 6-px body on the bottom 2 lines, a 2-px dome,
    a barrel from the dome at the angle (a pixel 1.82 lines wide). The
    client's table (tools/arc/mktank_arc.py) is made from this."""
    import math
    rows = [0] * 8
    rows[7] = 0b01111110
    rows[6] = 0b01111110
    rows[5] = 0b00011000
    a = math.radians(angle)
    for t in range(1, 4):
        x = 3.5 + t * 0.9 * math.cos(a)
        y = 4.5 - t * 1.6 * math.sin(a)
        xi, yi = int(round(x)), int(round(y))
        if 0 <= xi < 8 and 0 <= yi < 8:
            rows[yi] |= 0x80 >> xi
    return rows


def rect(i):
    """block graphics cell i (6 bits): 3x2 blocks, b2 b1 b0 the top row's
    left (3 px), middle (3), right (2); b5 b4 b3 the bottom's"""
    top = (3 if i & 1 else 0) | (0x1C if i & 2 else 0) | (0xE0 if i & 4 else 0)
    bot = (3 if i & 8 else 0) | (0x1C if i & 16 else 0) | (0xE0 if i & 32 else 0)
    return (top,) * 4 + (bot,) * 4


RECTS = [rect(i) for i in range(64)]


class UVI:
    def __init__(self):
        self.m = bytearray(0x300)

    def poke(self, addr, data):
        """a CPU address $1800-$1AFF (or an offset into it)"""
        if isinstance(data, int):
            data = [data]
        o = addr - 0x1800 if addr >= 0x1800 else addr
        self.m[o:o + len(data)] = bytes(data)

    def glyph(self, g):
        if g >= 0x38:
            o = 0x180 + (g - 0x38) * 8
            return tuple(self.m[o:o + 8])
        return GLYPHS[g]

    def frame(self):
        m = self.m
        pal = m[0x1F8:0x1FC]
        multi = m[0xFD] & 0x80
        gfx0 = bool(pal[0] & 0x80)
        lines26 = pal[0] & 0x40
        dbl = not (pal[1] & 0x80)
        ypos = 255 - m[0xFC]
        shift = m[0xFE] >> 5
        h = 16 if dbl else 8
        border = pal[1] & 7
        bm = [[border] * W for _ in range(H)]
        for line in range(H):
            if line < ypos:
                continue                        # (border)
            cl = (line - ypos) // h
            if (line - ypos) % h:
                continue
            if cl < 13:
                row = m[cl * 16:cl * 16 + 16]
            elif lines26 and cl < 26:
                row = m[0x200 + (cl - 13) * 16:0x200 + (cl - 13) * 16 + 16]
            else:
                continue
            gfx = gfx0
            for j in range(16):
                ch = row[j]
                if ch & 0x3F == 0:
                    if ch == 0xC0:
                        gfx = True
                    elif ch == 0x40:
                        gfx = False
                pic = RECTS[ch & 0x3F] if gfx else self.glyph(ch & 0x3F)
                if multi:
                    cc = (pal[1] >> 3) & 7 if ch & 0x40 else (pal[0] >> 3) & 7
                    sc = pal[1] & 7 if ch & 0x80 else pal[0] & 7
                else:
                    cc = ((pal[1] >> 3) & 1) | ((ch >> 5) & 6)
                    sc = pal[1] & 7
                x0 = XPOS + shift + j * 8
                for k in range(8):
                    b = pic[k]
                    for r in ((line + 2 * k, line + 2 * k + 1) if dbl else (line + k,)):
                        if r >= H:
                            continue
                        lr = bm[r]
                        for px in range(8):
                            if x0 + px < W:
                                lr[x0 + px] = cc if b & (0x80 >> px) else sc
        for i in range(4):
            y = 256 - m[0xF0 + 2 * i] if m[0xF0 + 2 * i] else 256
            x = m[0xF1 + 2 * i] - 43
            if y <= 0 or y >= H - 8 or x <= -XPOS or x >= 128 + XPOS - 8:
                continue
            reg = pal[3] if i < 2 else pal[2]
            col = (reg >> 3) & 7 if i % 2 == 0 else reg & 7
            sdbl = not (reg & (0x80 if i % 2 == 0 else 0x40))
            pic = m[0x180 + i * 8:0x188 + i * 8]
            for k in range(8):
                for r in ((y + 2 * k, y + 2 * k + 1) if sdbl else (y + k,)):
                    if r >= H:
                        continue
                    for px in range(8):
                        if pic[k] & (0x80 >> px):
                            bm[r][x + XPOS + px] = col
        return bm


def to_image(bm, scale=False):
    """an RGB PIL image; scale: as a TV shows it (4:3, a pixel 1.82 lines wide;
    FujiBlast's tools/arc/preview.py), each line 2 pixels tall"""
    from PIL import Image
    im = Image.new("P", (W, H))
    im.putpalette([c for rgb in COLORS for c in rgb])
    im.putdata([c for row in bm for c in row])
    if scale:
        im = im.resize((round(W * 2 * 262 * 4 / 3 / 192), H * 2), Image.NEAREST)
    return im
