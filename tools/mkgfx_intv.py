#!/usr/bin/env python3
"""mkgfx_intv.py ART_DIR GEN_DIR -- FujiBarrage's Intellivision art as
IntyBASIC (GEN_DIR/gfx.bas): the GRAM map's constants, the fixed cards
(gram_fixed: solid, levels, tanks, arrow, chute, stars) and the title's
logo (gram_logo, and logo_cell: where each goes) in DEFINE's form (4 words
a card, two rows a word, the first in the low byte), and the colour tables
(the skies' rows, the dirt, the seats, the fire). tools/intvart.py holds
the art and the colours; tools/preview_intv.py draws the same."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import intvart as A  # noqa: E402


def words(rows):
    b = A.bits(rows)
    return [b[2 * i] | b[2 * i + 1] << 8 for i in range(4)]


def data(f, label, ws, per=8):
    f.write("%s:\n" % label)
    for i in range(0, len(ws), per):
        f.write("    DATA %s\n" % ", ".join("$%04X" % w for w in ws[i:i + per]))


def main():
    art = A.read_art(os.path.join(sys.argv[1], "art.txt"))
    out = os.path.join(sys.argv[2], "gfx.bas")
    fixed = [None] * A.G_HEAD
    fixed[A.G_SOLID] = ["#" * 8] * 8
    for k, lv in enumerate(A.levels()):
        fixed[A.G_LEVEL + k] = lv
    for k, ang in enumerate(A.TANK_ANGLES):
        fixed[A.G_TANK + k] = art["tank%d" % ang]
    fixed[A.G_ARROW] = art["arrow"]
    fixed[A.G_CHUTE] = art["chute"]
    fixed[A.G_CHUTE + 1] = art["chutetank"]
    fixed[A.G_STAR] = art["star1"]
    fixed[A.G_STAR + 1] = art["star2"]
    assert all(fixed), [i for i, x in enumerate(fixed) if x is None]
    cells, uniq = A.logo()
    with open(out, "w") as f:
        f.write("' GENERATED by tools/mkgfx_intv.py from gfx/intv/art.txt and tools/intvart.py.\n")
        for name in ("G_SOLID", "G_LEVEL", "G_TANK", "G_ARROW", "G_CHUTE", "G_STAR", "G_HEAD", "N_HEAD",
                     "G_POOL", "N_POOL", "G_LOGO"):
            f.write("    CONST %s = %d\n" % (name, getattr(A, name)))
        f.write("    CONST N_FIXED = %d\n" % len(fixed))
        f.write("    CONST N_LOGO = %d\n" % len(uniq))
        f.write("    CONST N_LOGO_CELLS = %d\n" % len(cells))
        f.write("    CONST N_SKIES = %d\n" % len(A.SKIES))
        f.write("    CONST N_FIRE = %d\n" % len(A.FIRE_FG))
        f.write("    CONST STAR_ROWS = %d\n" % A.STAR_ROWS)
        ws = []
        for rows in fixed:
            ws += words(rows)
        data(f, "gram_fixed", ws)
        ws = []
        for rows in uniq:
            ws += words(rows)
        data(f, "gram_logo", ws)
        # each logo cell: its BACKTAB index, its card (from G_LOGO), its colour
        cw = []
        for col, row, rows, line in cells:
            fg = A.WHITE if line == 0 else (A.YELLOW if row < 6 else A.RED)
            cw += [row * 20 + col, uniq.index(rows), fg]
        f.write("logo_cell:\n")
        for i in range(0, len(cw), 12):
            f.write("    DATA %s\n" % ", ".join(str(v) for v in cw[i:i + 12]))
        # a sky's rows' background colours, the skies one after another
        f.write("sky_col:\n")
        for s in A.SKIES:
            f.write("    DATA %s\n" % ", ".join(str(c) for c in s))
        f.write("dirt_col:\n    DATA %s\n" % ", ".join(str(c) for c in A.DIRT))
        # a seat's MOB colour word (bits 0-2 and 12) and its HUD bar (background) and text
        f.write("seat_mob:\n    DATA %s\n" % ", ".join("$%04X" % ((c & 7) | (c & 8) << 9) for c in A.SEATS))
        f.write("seat_col:\n    DATA %s\n" % ", ".join(str(c) for c in A.SEATS))
        f.write("seat_txt:\n    DATA %s\n" % ", ".join(str(A.BLACK if c in A.LIGHT else A.WHITE)
                                                       for c in A.SEATS))
        f.write("fire_fg:\n    DATA %s\n" % ", ".join(str(c) for c in A.FIRE_FG))
    print("%s: %d fixed cards, logo %d cards in %d cells" % (out, len(fixed), len(uniq), len(cells)))


if __name__ == "__main__":
    main()
