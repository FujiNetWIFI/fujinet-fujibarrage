#!/usr/bin/env python3
"""mksfx_dos.py -- the PC's sound data (src/msdos/sound.c, the PC speaker):
tools/mksfx_coco.py's effects and tunes (the Intellivision's effects, the
tunes through tools/mus.py and its voicing) in the PC's units, written as
wasm data.

    mksfx_dos.py sfx OUT.asm
    mksfx_dos.py tunes OUT.asm NAME=music/x.txt ...

A pitch is the PIT's divisor for the speaker (1193182 Hz / f). A noise is
the middle of the divisors the speaker wanders through (sound.c: a random
one each tick); its random bits' rate R heard as about R / 6 Hz.
_vol_lin is the volume as it is (0-15): the speaker has none, sound.c
sounds a voice from its threshold up. _bl_units: a whistle's or blip's
pitch p (the Apple's AY period 2 (p+1) at 1020484 Hz) as a divisor.
The layout is mksfx_coco.py's (effects' pitches high byte first; tunes a
little-endian word a step, a call's and a jump's target an address).
"""
import os
import re
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import mksfx_coco as mc     # noqa: E402

PIT = 1193182.0


def pc_units(m, hz, noise=False):
    if noise:
        f = min(6000.0, max(40.0, hz / 6))
    else:
        f = hz
    return max(40, min(65535, round(PIT / max(f, 18.3))))


def num(tok):
    tok = tok.strip()
    if tok.startswith("$"):
        return "0%Xh" % int(tok[1:], 16)
    if re.match(r"^-?\d+$", tok):
        return tok
    return "OFFSET DGROUP:" + tok


def to_wasm(src, title):
    out = ["; GENERATED by tools/msdos/mksfx_dos.py (%s): edit the sources, not this." % title,
           "        .8086", "DGROUP  GROUP   _DATA", "_DATA   SEGMENT WORD PUBLIC 'DATA'"]
    for line in src.splitlines():
        if not line.strip() or line.startswith("*") or line.strip().startswith("section"):
            continue
        m = re.match(r"^\s+export\s+(.*)$", line)
        if m:
            out.append("        PUBLIC  " + ", ".join(t.strip() for t in m.group(1).split(",")))
            continue
        m = re.match(r"^(\S+)?\s+(fcb|fdb)\s+(.*)$", line)
        if m:
            lab, op, args = m.groups()
            d = "DB" if op == "fcb" else "DW"
            vals = ", ".join(num(t) for t in args.split(","))
            out.append("%-15s %s      %s" % (lab or "", d, vals))
            continue
        m = re.match(r"^(\S+)\s*$", line)
        if m:
            out.append("%s LABEL BYTE" % m.group(1))
            continue
        raise SystemExit("mksfx_dos: can't take: " + line)
    out += ["_DATA   ENDS", "        END"]
    return "\n".join(out) + "\n"


def main():
    what, dst = sys.argv[1], sys.argv[2]
    mc.units = pc_units
    mc.VMAX["pc"] = 15
    with tempfile.TemporaryDirectory() as td:
        tmp = os.path.join(td, "out.asm")
        if what == "sfx":
            mc.sfx("pc", os.path.join(HERE, "..", "..", "src", "intv", "sfx.asm"), tmp)
            text = open(tmp).read()
            # (the volumes as they are: the speaker's threshold is sound.c's)
            text = re.sub(r"_vol_lin\n(\s+fcb[^\n]*\n)+",
                          "_vol_lin\n        fcb     " + ",".join("$%02X" % v for v in range(16)) + "\n", text)
        elif what == "tunes":
            mc.tunes("pc", tmp, [a.split("=", 1) for a in sys.argv[3:]])
            text = open(tmp).read()
        else:
            sys.exit(__doc__)
    os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
    open(dst, "w").write(to_wasm(text, what))


if __name__ == "__main__":
    main()
