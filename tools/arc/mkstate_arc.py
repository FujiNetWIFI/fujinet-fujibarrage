#!/usr/bin/env python3
"""mkstate_arc.py PROTO.h CATEQU.inc STATE.inc -- the offline screen scenes'
STATE (src/arcadia/src/p_tscr.inc: test scenes 4 on; tools/arcsim/scenes/
t*.txt): a canned ST, as the server would send it, for the waiting room,
the shop, the results and the field's UI. Our seat is 0 and hosts; seats
1-2 and 5-6 are bots of several tiers, 4 a person whose link is down, 3
empty; a cash past 16 bits, items to buy, sell and use; the build's
catalog's length and sums (so the screens trust it). Writes TSTATE: DB.
"""
import re
import sys


def main(proto, catequ, out):
    P = {}
    for line in open(proto):
        m = re.match(r"#define (\w+)\s+(-?\d+)$", line.strip())
        if m:
            P[m.group(1)] = int(m.group(2))
    C = {}
    for line in open(catequ):
        m = re.match(r"(\w+)\s+EQU\s+(\d+)", line)
        if m:
            C[m.group(1)] = int(m.group(2))
    st = bytearray(P["STATE_SIZE"])
    st[P["OFF_PHASE"]] = P["PH_WAIT"]
    st[P["OFF_ROUND"]] = 2
    st[P["OFF_ROUNDS"]] = 5
    st[P["OFF_HOST"]] = 0
    st[P["OFF_TURN"]] = 0
    st[P["OFF_TIMER"]] = 45
    w = -137 & 0xFFFF
    st[P["OFF_WIND"]:P["OFF_WIND"] + 2] = bytes([w & 255, w >> 8])
    st[P["OFF_RESULT"]] = 2
    st[P["OFF_MY_SEAT"]] = 0
    n = C["CATLEN"]
    st[P["OFF_CAT_LEN"]:P["OFF_CAT_LEN"] + 2] = bytes([n & 255, n >> 8])
    st[P["OFF_CAT_SUM"]] = C["CATS1"]
    st[P["OFF_CAT_SUM"] + 1] = C["CATS2"]
    sets = {"SET_SKY": 2, "SET_BUMPINESS": 8, "SET_SLOPE": 6, "SET_MAX_WIND": 8, "SET_GRAVITY": 19,
            "SET_VISCOSITY": 3, "SET_SUSPEND": 2, "SET_TANKS_FALL": 1, "SET_SCALE": 1, "SET_BORDERS": 2,
            "SET_WALLS": 3, "SET_TANKS": 4, "SET_ROUNDS": 4, "SET_MODE": 0, "SET_ORDER": 3,
            "SET_TIMER": 4, "SET_TALK": 2, "SET_TALK_PCT": 5, "SET_ARMS": 4, "SET_CASH": 40,
            "SET_INTEREST": 2, "SET_BOTS_BUY": 1}
    for k, v in sets.items():
        st[P["OFF_SETTINGS"] + P[k]] = v
    seats = [("ARC", P["KIND_HUMAN"], 0, 3), ("SPARKY", P["KIND_BOT"], 2, 1),
             ("BOOMER", P["KIND_BOT"], 5, 0), None, ("THOMC", P["KIND_HUMAN"], 0, 0),
             ("GIZMO", P["KIND_BOT"], 7, 2), ("WIDGETRS", P["KIND_BOT"], 4, 0), None, None, None]
    for s, d in enumerate(seats):
        if not d:
            continue
        o = P["OFF_SEATS"] + s * P["SEAT_SIZE"]
        name, kind, tier, wins = d
        st[o + P["P_NAME"]:o + P["P_NAME"] + len(name)] = name.encode()
        st[o + P["P_KIND"]] = kind
        st[o + P["P_TIER"]] = tier
        st[o + P["P_ENERGY"]] = 100
        st[o + P["P_ANGLE"]] = 45 + 10 * s
        st[o + P["P_POWER"]:o + P["P_POWER"] + 2] = bytes([500 & 255, 500 >> 8])
        st[o + P["P_WEAPON"]] = 1 if s == 0 else 0
        fl = P["PF_ALIVE"]
        if not (kind == P["KIND_HUMAN"] and name == "THOMC"):
            fl |= P["PF_CONN"]
        st[o + P["P_FLAGS"]] = fl
        st[o + P["P_WINS"]] = wins
    cash = 1234567
    st[P["OFF_CASH"]:P["OFF_CASH"] + 4] = cash.to_bytes(4, "little")
    inv = {1: 5, 2: 3, 3: 1, 7: 1, 10: 20, 33: 6, 34: 2, 38: 20, 39: 8, 40: 10, 42: 3, 44: 2,
           46: 1, 47: 25}
    for i, k in inv.items():
        st[P["OFF_INV"] + i] = k
    L = ["; GENERATED by tools/arc/mkstate_arc.py -- do not edit.", "TSTATE:"]
    for i in range(0, len(st), 16):
        L.append("        DB      " + ",".join("$%02X" % b for b in st[i:i + 16]))
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
