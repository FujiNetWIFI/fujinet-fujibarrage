#!/usr/bin/env python3
"""mktitle_chf.py -- the title's field scene (checkpoint 1's): hills, two
tanks, a shell's arc and its burst, FUJIBARRAGE in 2x red letters over the
sky (title.inc, page BOOT: drawn into the field, then FSHOW).

    mktitle_chf.py OUT.inc

TTERR: a TERRAIN entry a column (dirt from that row down). TTPIX: x, y,
code (port-1: tank $80, fire $40) for every pixel over the hills; FF ends.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mkfont import GLYPHS                      # noqa: E402

FW, FH = 102, 46
TANK, FX = 0x80, 0x40


def main():
    tops = [int(28 + 5 * math.sin(x / 9.0) + 3 * math.sin(x / 4.0)) for x in range(FW)]
    px = {}
    for tx in (18, 82):
        top = tops[tx]
        for dx, dy in [(-1, -3), (0, -3), (1, -3)] + [(d, r) for d in range(-2, 3) for r in (-2, -1)]:
            px[(tx + dx, top + dy)] = TANK
        for k in (1, 2, 3):
            px[(tx + (k if tx < 50 else -k), top - 3 - k)] = TANK
    for t in range(0, 61, 2):
        x = 22 + t
        y = int(22 - 0.022 * (60 * t - t * t)) - 4
        if 0 <= y < tops[x] and (x, y) not in px:
            px[(x, y)] = FX
    cx, cy, rx, ry = 80, 22, 5, 4
    for y in range(FH):
        for x in range(FW):
            if (x - cx) ** 2 * ry * ry + (y - cy) ** 2 * rx * rx <= rx * rx * ry * ry and y < tops[x] \
                    and (x, y) not in px:
                px[(x, y)] = FX
    x0, y0 = 7, 2
    for ch in "FUJIBARRAGE":
        g = GLYPHS[ch].split(";")
        for gy, line in enumerate(g):
            for gx, c in enumerate(line):
                if c == "#":
                    for dy in range(2):
                        for dx in range(2):
                            px[(x0 + 2 * gx + dx, y0 + 2 * gy + dy)] = FX
        x0 += 8
    L = ["; GENERATED by tools/chf/mktitle_chf.py -- do not edit."]
    L.append("TTERR:")
    for i in range(0, FW, 16):
        L.append("        DB " + ",".join(str(t) for t in tops[i:i + 16]))
    L.append("TTPIX:")
    items = sorted(px.items())
    for i in range(0, len(items), 8):
        L.append("        DB " + ", ".join("%d,%d,%d" % (x, y, c) for (x, y), c in items[i:i + 8]))
    L.append("        DB 0FFH")
    L.append("; %d pixels" % len(items))
    open(sys.argv[1], "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
