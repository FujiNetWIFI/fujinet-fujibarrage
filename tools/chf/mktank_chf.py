#!/usr/bin/env python3
"""mktank_chf.py -- the Channel F's tank: its body and barrel (tank.inc).

    mktank_chf.py OUT.inc

A tank is 5x3 (x its centre, y the row under it): a 3-wide turret over a
5-wide hull, then a barrel of 4 pixels from the turret's top at the angle
(0 right, 90 up, 180 left). A pixel is ~0.76 as wide as it is tall
(client.ChannelF's PAR 48), so the barrel's rise is 3/4 of its run's to
look round: k pixels out is (k cos a, 3/4 k sin a). BARL: for each 5
degrees (37), 4 (dx, dy) pairs, dy up (subtracted).
"""
import math
import sys

BODY = [".###.", "#####", "#####"]


def main():
    L = ["; GENERATED by tools/chf/mktank_chf.py -- do not edit."]
    pix = []
    for r, row in enumerate(BODY):
        for c, ch in enumerate(row):
            if ch == "#":
                pix.append((c - 2, r - len(BODY)))
    L.append("TKBODYN EQU %d" % len(pix))
    L.append("TKBODY: DB " + ", ".join("%d,%d" % (dx & 0xFF, dy & 0xFF) for dx, dy in pix))
    L.append("BARL:")
    for i in range(37):
        a = math.radians(5 * i)
        row = []
        for k in range(1, 5):
            dx = int(round(k * math.cos(a)))
            dy = int(round(k * math.sin(a) * 0.75))
            row.append("%d,%d" % (dx & 0xFF, dy & 0xFF))
        L.append("        DB " + ", ".join(row) + "  ; %d" % (5 * i))
    open(sys.argv[1], "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
