#!/usr/bin/env python3
"""mkcat_astro.py CATALOG.bin OUT.inc -- the server's CATALOG (barraged
-catalog) as the Astrocade's CAT page keeps it: its 4K of RAM has no room
for the 1612 bytes the server sends, so they live in ROM, indexed here
(src/cat.c's cat_check, done at build time), and the link drops the K
frames. The STATE's OFF_CAT_LEN and OFF_CAT_SUM are checked against CATLEN,
CATS1, CATS2: a server whose catalog differs gets "UPDATE FUJIBARRAGE".

    CITEMS   48 x 8: kind, arms, bundle, price (3 bytes), DW its name
    CSETS    27 x 8: page, type (0 choice, 1 number), count, decimals,
             DW its label, DW its data (a choice: DW a name each; a
             number: DW min, DW step)
    CPAGES   DW a page's name each      CTIERS  DW a tier's name each
    strings  NUL-ended, ASCII
"""
import sys


def main(src, out):
    cat = open(src, "rb").read()
    s1 = s2 = 0
    for b in cat:
        s1 = (s1 + b) % 255
        s2 = (s2 + s1) % 255
    nitems, nsets, npages = cat[1], cat[2], cat[3]
    strings = []                    # (label, text)

    def lstr(at, name):
        n = cat[at]
        strings.append((name, cat[at + 1:at + 1 + n].decode("ascii")))
        return at + 1 + n

    at = 4
    for p in range(npages):
        at = lstr(at, "CP%d" % p)
    items = []
    for i in range(nitems):
        rec = cat[at:at + 6]
        at = lstr(at + 6, "CI%d" % i)
        items.append(rec)
    sets = []
    for k in range(nsets):
        page, typ = cat[at], cat[at + 1]
        at = lstr(at + 2, "CSL%d" % k)
        if typ == 0:
            n = cat[at]
            at += 1
            for j in range(n):
                at = lstr(at, "CSV%d_%d" % (k, j))
            sets.append((page, typ, n, 0, ["CSV%d_%d" % (k, j) for j in range(n)]))
        else:
            mn, step, cnt, dec = cat[at] | cat[at + 1] << 8, cat[at + 2] | cat[at + 3] << 8, cat[at + 4], cat[at + 5]
            at += 6
            sets.append((page, typ, cnt, dec, (mn, step)))
    ntiers = cat[at]
    at += 1
    for t in range(ntiers):
        at = lstr(at, "CT%d" % t)
    assert at == len(cat), (at, len(cat))

    L = ["; GENERATED by tools/astro/mkcat_astro.py from the server's CATALOG -- do not edit.",
         "CATLEN  EQU     %d" % len(cat), "CATS1   EQU     %d" % s1, "CATS2   EQU     %d" % s2,
         "CNITEMS EQU     %d" % nitems, "CNSETS  EQU     %d" % nsets, "CNPAGES EQU     %d" % npages,
         "CNTIERS EQU     %d" % ntiers, "CITEMS:"]
    for i, r in enumerate(items):
        L.append("        DB      %d,%d,%d,%d,%d,%d" % tuple(r) + "\n        DW      CI%d" % i)
    L.append("CSETS:")
    data = []
    for k, (page, typ, cnt, dec, d) in enumerate(sets):
        L.append("        DB      %d,%d,%d,%d\n        DW      CSL%d,CSD%d" % (page, typ, cnt, dec, k, k))
        if typ == 0:
            data.append("CSD%d:   DW      %s" % (k, ",".join(d)))
        else:
            data.append("CSD%d:   DW      %d,%d" % (k, d[0], d[1]))
    L += data
    L.append("CPAGES: DW      %s" % ",".join("CP%d" % p for p in range(npages)))
    L.append("CTIERS: DW      %s" % ",".join("CT%d" % t for t in range(ntiers)))
    for name, text in strings:
        assert '"' not in text and "\\" not in text, text
        L.append('%-8sDB      "%s",0' % (name + ":", text) if text else "%-8sDB      0" % (name + ":"))
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
