#!/usr/bin/env bash
# build.sh -- FujiBarrage for the Fairchild Channel F: a protocol 2 (APPBANK)
# image -- the fixed 16K and six 8K pages, 64K (barrage.asm). FujiBlast's
# src/channelf/build.sh, for this tree.
#
#   src/channelf/build.sh               r2r/channelf/barrage.bin
#   OUT=dir R2R=dir                     where the objects and the image go
#   DEFSRV=host:port                    the server without the lobby's key
#                                       (default gen/server, never rewritten here)
#   SETTLE=mule|pal|bios|N              clocks after a VRAM strobe before the next
#                                       port write: 94 (M.U.L.E.'s, default),
#                                       105 (94's time at a PAL console's 2 MHz),
#                                       136 (the BIOS's)
#   ASL=, P2BIN=                        the assembler (default ~/asl)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/channelf}"
R2R="${R2R:-$ROOT/r2r/channelf}"
T="$ROOT/tools/chf"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
[ -x "$ASL" ]   || { echo "build.sh: no assembler at $ASL" >&2; exit 1; }
[ -x "$P2BIN" ] || { echo "build.sh: no p2bin at $P2BIN" >&2; exit 1; }
mkdir -p "$OUT" "$R2R"
OUT="$(cd "$OUT" && pwd)"

case "${SETTLE:-mule}" in
    mule) settle=94 ;;
    pal)  settle=105 ;;
    bios) settle=136 ;;
    *)    settle="$SETTLE" ;;
esac

python3 "$T/mkproto.py" "$ROOT/src/proto.h" "$OUT/proto.inc"
python3 "$T/mkfont.py" "$OUT/font.inc"
python3 "$T/mkspike.py" "$OUT/spike.inc"
python3 "$T/mktank_chf.py" "$OUT/tankgfx.inc"
python3 "$T/mktitle_chf.py" "$OUT/title.inc"
python3 "$T/mksnd_chf.py" "$OUT/snd.inc"
DEFSRV="${DEFSRV:-$(cat "$ROOT/gen/server" 2>/dev/null || echo fujinet.online:9913)}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'DEFSPEC: DB "N:TCP://%s/",0\n' "$DEFSRV"
  printf 'DEFURL:  DB "tcp://%s/?table=",0\n' "$DEFSRV"
} > "$OUT/config.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  echo "SETTLE  EQU $settle"
  echo "DEBUG   EQU ${DEBUG:-0}"
} > "$OUT/flags.inc"

python3 "$T/checkdup.py" "$HERE/barrage.asm" "$HERE"/src/*.inc
ln -sfn "$HERE" "$OUT/srcdir"
(cd "$OUT" && "$ASL" srcdir/barrage.asm -L -i . -q -o barrage.p -olist barrage.lst) || {
    grep -B1 -A3 "Error\|error" "$OUT/barrage.lst" | head -40 >&2
    echo "build.sh: asl failed (see $OUT/barrage.lst)" >&2
    exit 1
}
"$P2BIN" "$OUT/barrage.p" "$R2R/barrage.bin" -r 0x0000-0xffff -l 0xff -q
rm -f "$OUT/barrage.p"

python3 "$T/checkrom.py" "$R2R/barrage.bin"
python3 "$T/checksize.py" "$OUT/barrage.lst"
python3 "$T/checkcalls.py" "$HERE/src"
python3 "$T/checkacc.py" "$HERE"/src/*.inc "$HERE/barrage.asm"
python3 "$T/checkdepth.py" --max 21 "$HERE/barrage.asm" "$HERE"/src/*.inc
