#!/usr/bin/env python3
"""mkfont_a78.py -- the 7800's text font for MARIA's 320A (ca65, segment
FONT: REPL's first 2K, CHARBASE $80).

    mkfont_a78.py OUT.s

The Namco 8x8 font (gfx/coco/namco.bin, ' ' to '_': an Atari screen code's
glyph), 256 codes: code & 63 the glyph, + 64 its inverse (rows 0-6 only:
row 7 stays blank, as every glyph's is, so a row's colours can change on
its last line: src/atari7800/maria.s), + 128 the same again (a label's:
src/atari7800/scr.c). MARIA reads a character's line l (0 the top) from
page CHARBASE + 7 - l (its OFFSET counts down), at the code's byte.
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")


def main():
    font = open(os.path.join(ROOT, "gfx", "coco", "namco.bin"), "rb").read()[:512]
    assert all(font[g * 8 + 7] == 0 for g in range(64))
    out = ["; GENERATED by tools/atari7800/mkfont_a78.py: do not edit.",
           '        .segment "FONT"',
           "        .export _font_a78",
           "_font_a78:"]
    for page in range(8):
        line = 7 - page
        data = []
        for code in range(256):
            b = font[(code & 63) * 8 + line]
            if code & 64 and line < 7:
                b ^= 0xFF
            data.append(b)
        out.append("; line %d" % line)
        for i in range(0, 256, 16):
            out.append("        .byte   " + ", ".join("$%02X" % b for b in data[i:i + 16]))
    open(sys.argv[1], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
