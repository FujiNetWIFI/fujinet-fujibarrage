#!/usr/bin/env python3
"""mkgfx_coco.py -- the CoCo's art, as lwasm data (FB_SECT-free: each file
names its own section).

    mkgfx_coco.py font2 OUT.asm     the CoCo 1/2's text font: 64 glyphs
                                    (ASCII 32-95) of 8 rows, each row a
                                    nibble (3 pixels and a gap; bit 3 the
                                    left pixel), from gfx/coco/font3x7.png
                                    (FujiBlast's gfx/hgr/font3.png): 512 bytes
    mkgfx_coco.py font3 OUT.asm     the CoCo 3's: 96 glyphs (ASCII 32-127)
                                    of 8 rows of 8 pixels (bit 7 the left),
                                    gfx/coco/namco.bin: 768 bytes
    mkgfx_coco.py pal3 OUT.asm      the CoCo 3's text screens' palette, RGB
                                    and composite codes (16 each)
    mkgfx_coco.py fld3 OUT.asm      the CoCo 3's field: the skies' and the
                                    dirt palettes' colours, the fire's
                                    cycle, the dither and star patterns
                                    (src/coco3/fld3.asm's rows), the tank
    mkgfx_coco.py tank2 OUT.asm     the CoCo 1/2's tank: body, barrels,
                                    pennant (the Apple's, at its PAR)
    mkgfx_coco.py --preview3 OUT.png  the CoCo 3's eight skies over the eight
                                    dirts, RGB above composite

The CoCo 3's palette indices (src/coco3/): 0 black; on the field 1-2 sky,
3-4 dirt, 5 fire, on the text screens 1-5 the rows' grounds and the dim
text; 6-15 the seats' colours on both (seat 7 white: the text's ink).

The fonts go in the art section (src/coco/barrage{,3}.link: $E000), which
the program's high file brings (src/coco/bank.c).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def font2():
    from PIL import Image
    im = Image.open(os.path.join(ROOT, "gfx", "coco", "font3x7.png")).convert("L")
    px = im.load()
    out = []
    for g in range(64):
        for y in range(8):
            m = 0
            for x in range(4):
                if px[g * 4 + x, y] > 128:
                    m |= 8 >> x
            out.append(m)
    return out


def font3():
    f = open(os.path.join(ROOT, "gfx", "coco", "namco.bin"), "rb").read()
    assert len(f) == 768
    return list(f)


# the seats' colours: the Atari's hues (src/atari/scr.c seat_col), seat 7 white
SEATS = [(255, 85, 85), (85, 85, 255), (85, 255, 85), (255, 255, 85), (170, 85, 255),
         (85, 255, 255), (255, 170, 0), (255, 255, 255), (255, 170, 170), (170, 170, 0)]
# the text screens' rows, as the Atari's (src/atari/scr.c pal): 1 blue (TEXT's
# ground), 2 red (TITLE's), 3 grey (HEAD's), 4 yellow (HILITE's), 5 dim ink
TEXT = [(0, 0, 0), (0, 0, 170), (170, 0, 0), (85, 85, 85), (255, 255, 85), (170, 170, 170)]


def pal3():
    import cocopal
    cols = TEXT + SEATS
    return [cocopal.rgb_code(c) for c in cols] + [cocopal.cmp_code(c) for c in cols]


def emit(path, label, data, what):
    emit_many(path, [(label, data)], what)


def emit_many(path, tables, what):
    with open(path, "w") as o:
        o.write("* GENERATED by tools/mkgfx_coco.py: %s. Do not edit.\n" % what)
        o.write("        section art\n")
        for label, data in tables:
            o.write("        export  %s\n%s\n" % (label, label))
            for i in range(0, len(data), 16):
                o.write("        fcb     %s\n" % ",".join("$%02X" % (b & 255) for b in data[i:i + 16]))


# ---- the CoCo 3's field ------------------------------------------------------
# A round's palette (src/coco/field.c): 0 black, 1-2 the sky's two colours
# (A at the top, B at the horizon, dithered between), 3-4 the dirt's (D0
# near the surface, D1 deep), 5 the fire, 6-15 the seats. By SKY_*: plain,
# gradient, stars, storm, sunset, cavern, black, random (the server picks
# one: as gradient).
SKY3 = [
    ((85, 170, 255), (85, 170, 255)),       # plain: day blue
    ((0, 0, 85), (85, 170, 255)),           # gradient: night to day
    ((0, 0, 0), (255, 255, 255)),           # stars: black, white stars
    ((0, 0, 0), (170, 170, 170)),           # storm: black to grey
    ((85, 0, 170), (255, 170, 0)),          # sunset: purple to orange
    ((0, 0, 0), (85, 0, 0)),                # cavern: black over dark red
    ((0, 0, 0), (0, 0, 0)),                 # black
    ((0, 0, 85), (85, 170, 255)),           # random: as gradient
]
# the dirt palettes (the Atari's hues, src/atari/dlc.s dirt_hue): bright, dark
DIRT3 = [
    ((255, 170, 85), (170, 85, 0)),         # brown-orange
    ((85, 170, 0), (0, 85, 0)),             # green
    ((170, 170, 170), (85, 85, 85)),        # grey
    ((255, 85, 0), (170, 0, 0)),            # red-orange
    ((255, 170, 0), (85, 85, 0)),           # gold
    ((85, 85, 255), (0, 0, 85)),            # blue
    ((170, 85, 255), (85, 0, 85)),          # purple
    ((255, 255, 85), (170, 85, 0)),         # yellow-orange
]
# the fire's colours a frame each while it burns (index 0: still)
FIRE3 = [(255, 255, 255), (255, 255, 85), (255, 255, 0), (255, 170, 0),
         (255, 85, 0), (255, 0, 0), (255, 85, 0), (255, 170, 0)]
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
N_STARS = 16                    # star rows' patterns, 64 bytes (128 pixels) each
LEVELS = 17


def codes(cols):
    import cocopal
    return [cocopal.rgb_code(c) for c in cols], [cocopal.cmp_code(c) for c in cols]


def dither(a, b):
    """level 0-16 x row phase 0-3: two bytes (four pixels) of colours a/b"""
    out = []
    for lv in range(LEVELS):
        for ph in range(4):
            px = [b if lv > BAYER[ph][x] else a for x in range(4)]
            out += [px[0] << 4 | px[1], px[2] << 4 | px[3]]
    return out


def stars():
    import random
    rnd = random.Random(1987)
    out = []
    for k in range(N_STARS):
        px = [1] * 128
        for _ in range(1 + (k % 3 == 0)):
            x = rnd.randrange(128)
            px[x] = 2
            if rnd.random() < 0.25 and x < 127:     # a bright one: two wide
                px[x + 1] = 2
        out += [px[2 * i] << 4 | px[2 * i + 1] for i in range(64)]
    return out + out[:64]               # (a row may start anywhere in the first N: 63 bytes on)


def floor5(v):
    import math
    return int(math.floor(v + 0.5))


def barrels(length, par, steps, oy, mirror0):
    """19 angles (0, 5, ... 90): steps points each from (0, oy), a line of
    length pixels wide (its height in lines x par/64), duplicates dropped
    and the last repeated; mirror0: past 90, x becomes mirror0 - x"""
    import math
    out = []
    for a in range(0, 95, 5):
        r = math.radians(a)
        dx, dy = length * math.cos(r), length * math.sin(r) * par / 64
        pts = []
        for k in range(1, steps + 1):
            p = (floor5(dx * k / steps), oy - floor5(dy * k / steps))
            if p != (0, oy) and p not in pts:
                pts.append(p)
        while len(pts) < steps:
            pts.append(pts[-1])
        for x, y in pts[:steps]:
            out += [x, y]
    return out


def shape(rows, ch, x0, y0):
    """the pixels of character ch in rows (top first) as (dx, dy) pairs from
    (x0, y0) for the top-left one; a count first"""
    pts = []
    for j, row in enumerate(rows):
        for i, c in enumerate(row):
            if c == ch:
                pts += [x0 + i, y0 + j]
    return [len(pts) // 2] + pts


# the CoCo 3's tank, 12 by 6 over its foot (x, y): columns x-6 .. x+5
TANK3 = [
    "....SSSS....",
    "...SSHHSS...",
    ".SSSSSSSSSS.",
    "SSSSSSSSSSSS",
    "KSKSKSKSKSKS",
    ".KKKKKKKKKK.",
]
FLAG3 = [                                         # yours: a pennant, white
    ".WWW",
    ".WW.",
    ".W..",
    ".W..",
]


def fld3():
    sky = [c for pair in SKY3 for c in pair]
    dirt = [c for pair in DIRT3 for c in pair]
    srgb, scmp = codes(sky)
    drgb, dcmp = codes(dirt)
    frgb, fcmp = codes(FIRE3)
    t = [
        ("_sky3", srgb + scmp),                     # [sky*2 + k], RGB then composite (+16)
        ("_dirt3", drgb + dcmp),
        ("_fire3", frgb + fcmp),                    # 8 RGB, 8 composite
        ("_dith3", dither(1, 2)),                   # [level*8 + phase*2]
        ("_dithd3", dither(3, 4)),
        ("_star3", stars()),                        # [any of k*64], 64 on
        ("_tk3_body", shape(TANK3, "S", -6, -6)),
        ("_tk3_dark", shape(TANK3, "K", -6, -6)),
        ("_tk3_lite", shape(TANK3, "H", -6, -6)),
        ("_tk3_flag", shape(FLAG3, "W", -6, -10)),
        ("_tk3_barrel", barrels(8, 55, 8, -5, -1)),   # 19 x 8 points
    ]
    return t


# the CoCo 1/2's tank: the Apple's 5 by 5 (src/apple2/field.c), its barrel
# 3 pixels wide at PAR 109, the pennant
TANK2 = [
    "..S..",
    ".SSS.",
    "SSSSS",
    "SSSSS",
    "S.S.S",
]
FLAG2 = [
    ".SS",
    ".S.",
    ".S.",
]


def flip2():
    """a byte of PMODE 4 in the other artifact phase: each pair 01 <-> 10"""
    out = []
    for b in range(256):
        m = (b ^ (b >> 1)) & 0x55
        out.append(b ^ (m | m << 1))
    return out


def tank2():
    return [
        ("_tk2_body", shape(TANK2, "S", -2, -5)),
        ("_tk2_flag", shape(FLAG2, "S", -3, -8)),
        ("_tk2_barrel", barrels(3, 109, 5, -5, 0)),   # 19 x 5 points
    ]


def preview3(path):
    """each sky over a hill of dirt (palette k), as the CoCo 3 draws them
    (src/coco/field.c's rows): RGB left, composite right"""
    from PIL import Image
    import math
    import cocopal
    W, H = 320, 176
    im = Image.new("RGB", (2 * W + 8, 8 * (H + 4)))
    ds, dd, st = dither(1, 2), dither(3, 4), stars()
    for side in range(2):
        for k in range(8):
            pal = [(0, 0, 0)] * 16
            pal[1], pal[2] = SKY3[k]
            pal[3], pal[4] = DIRT3[k]
            pal[5] = FIRE3[0]
            if side:
                pal = [cocopal.show(cocopal.cmp_code(c), True) for c in pal]
            else:
                pal = [cocopal.show(cocopal.rgb_code(c)) for c in pal]
            for y in range(H):
                sp, sm = sky_row(k, y, ds, st)
                dp = dd[dirt_level(y) * 8 + (y & 3) * 2:][:2]
                for x in range(W):
                    top = 110 + int(30 * math.sin(x / 40.0 + k))
                    if y >= top:
                        b = dp[(x >> 1) & 1]
                    else:
                        b = sp[(x >> 1) & sm]
                    c = b >> 4 if x % 2 == 0 else b & 15
                    im.putpixel((side * (W + 8) + x, k * (H + 4) + y), pal[c])
    im = im.resize((im.width * 2, im.height * 2), Image.NEAREST)
    im.save(path)


def sky_row(sky, y, ds, st):
    """line y's sky pattern and its mask (src/coco/field.c's rows)"""
    if sky == 2 and star_row(y) is not None:
        k = star_row(y)
        return st[k * 64:k * 64 + 64], 63
    lv = sky_level(sky, y)
    return ds[lv * 8 + (y & 3) * 2:][:2], 1


def star_row(y):
    """the star pattern on line y of the stars sky, or None (field.c's)"""
    h = (y * 73 + 41) & 255
    return (h >> 2) % N_STARS if h < 96 else None


def sky_level(sky, y, h=176):
    """the sky's dither level on line y (src/coco/field.c's, for previews)"""
    if sky in (1, 3, 4, 7):
        return min(16, y * 17 // h)
    if sky == 5:
        return 0 if y < 80 else 16 if y >= 96 else (y - 80)
    return 0


def dirt_level(y, h=176):
    return min(16, y * 12 // h + (4 if (y // 9) % 3 == 1 else 0))


def main():
    what, out = sys.argv[1], sys.argv[2]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    if what == "font2":
        emit(out, "_font2", font2(), "the CoCo 1/2's 3x7 font, a nibble a row")
    elif what == "font3":
        emit(out, "_font3", font3(), "the CoCo 3's 8x8 font (Namco)")
    elif what == "pal3":
        emit(out, "_pal3_text", pal3(), "the CoCo 3's text palette: 16 RGB codes, then 16 composite")
    elif what == "fld3":
        emit_many(out, fld3(), "the CoCo 3's field: palettes, patterns, the tank")
    elif what == "tank2":
        emit_many(out, tank2(), "the CoCo 1/2's tank")
    elif what == "flip2":
        emit(out, "_flip2", flip2(), "the CoCo 1/2's artifact phase swap, a byte at a time")
    elif what == "--preview3":
        preview3(out)
    else:
        sys.exit("what? " + what)


if __name__ == "__main__":
    main()
