#!/usr/bin/env python3
"""mktab_a2.py -- the Apple II field's tables (src/apple2/fld.s): HGR page 1
as the field, 140 colour pixels by 160 lines.

    mktab_a2.py OUT.s

A colour pixel is two dots of a line, the game's value in them: bit 0 the
even dot (blue in palette 1, violet in 0), bit 1 the odd dot (orange, or
green); both white, neither black. Line y's 40 bytes start at
$2000 + (y & 7) * $400 + ((y >> 3) & 7) * $80 + (y >> 6) * $28 and never
cross a page. A byte holds 7 dots, the left one in bit 0 (bit 7 is the
palette), so pixel x's dots 2x and 2x + 1 lie in byte (2x) / 7 and
(2x + 1) / 7: the same byte, except pixel 3 of every 7.
"""
import sys

W, H = 140, 160


def row(y):
    return 0x2000 + (y & 7) * 0x400 + ((y >> 3) & 7) * 0x80 + (y >> 6) * 0x28


def main():
    rows = [row(y) for y in range(H)]
    b0 = [(2 * x) // 7 for x in range(W)]
    m0 = [1 << ((2 * x) % 7) for x in range(W)]
    b1 = [(2 * x + 1) // 7 for x in range(W)]
    m1 = [1 << ((2 * x + 1) % 7) for x in range(W)]
    assert all(r % 256 + 39 < 256 for r in rows)

    def dump(name, vals):
        out = ["_%s:" % name]
        for i in range(0, len(vals), 16):
            out.append("        .byte   " + ", ".join("$%02X" % v for v in vals[i:i + 16]))
        return out

    lines = ["; GENERATED by tools/mktab_a2.py: the field's tables (src/apple2/fld.s).",
             "        .export _rowlo, _rowhi, _xb0, _xm0, _xb1, _xm1",
             "        .segment \"LC\"  ; (the language card: src/apple2/barrage.cfg)"]
    lines += dump("rowlo", [r & 0xFF for r in rows])
    lines += dump("rowhi", [r >> 8 for r in rows])
    lines += ["; pixel x's even dot: its byte in the line, its bit; its odd dot's"]
    lines += dump("xb0", b0)
    lines += dump("xm0", m0)
    lines += dump("xb1", b1)
    lines += dump("xm1", m1)
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
