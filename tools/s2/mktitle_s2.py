#!/usr/bin/env python3
"""mktitle_s2.py -- the title's field scene (the Channel F's mktitle_chf.py
for the Studio II): hills, two tanks with their marks, a shell's dotted arc
and its burst; FUJIBARRAGE over the sky (src/studio2 p_room.inc title_scene).

    mktitle_s2.py OUT.inc

TTOPS: a TERRAIN entry a column (dirt from that line down). TTARC: x, y
of the arc's dots, FF ends. TT0X.. the tanks (x, the line under them, the
barrel's angle), TTBX.. the burst (centre, radii in dots and lines).
"""
import math
import sys

FW, FH = 64, 108
PAR = 210 / 64                                  # a dot is 3.28 lines wide


def main():
    tops = [min(FH - 4, int(84 + 7 * math.sin(x / 7.0 + 0.6) + 3 * math.sin(x / 3.1))) for x in range(FW)]
    t0x, t1x = 10, 53
    for tx in (t0x, t1x):                       # level under the hulls
        lv = min(tops[tx - 2:tx + 3])
        for x in range(tx - 2, tx + 3):
            tops[x] = lv
    bx = 45
    by = tops[bx] - 6
    brx, bry = 4, int(4 * PAR)
    x0, y0 = t0x + 3, tops[t0x] - 13
    arc = []
    for x in range(x0, bx - 3, 2):
        t = (x - x0) / (bx - x0)
        y = int(y0 + (by - y0) * t - 40 * 4 * t * (1 - t))
        if 26 <= y < tops[x]:                   # (under the title's row)
            arc.append((x, y))
    with open(sys.argv[1], "w") as f:
        f.write("; GENERATED by tools/s2/mktitle_s2.py: the title's field scene\n")
        f.write("TT0X    EQU     %d\nTT0Y    EQU     %d\nTT0A    EQU     55\n" % (t0x, tops[t0x]))
        f.write("TT1X    EQU     %d\nTT1Y    EQU     %d\nTT1A    EQU     125\n" % (t1x, tops[t1x]))
        f.write("TTBX    EQU     %d\nTTBY    EQU     %d\nTTBRX   EQU     %d\nTTBRY   EQU     %d\n"
                % (bx, by, brx, bry))
        f.write("TTOPS:\n")
        for i in range(0, FW, 16):
            f.write("        DB      " + ", ".join(str(v) for v in tops[i:i + 16]) + "\n")
        f.write("TTARC:\n")
        for i in range(0, len(arc), 8):
            f.write("        DB      " + ", ".join("%d, %d" % p for p in arc[i:i + 8]) + "\n")
        f.write("        DB      0FFH\n")


if __name__ == "__main__":
    main()
