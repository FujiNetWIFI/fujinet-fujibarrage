#!/usr/bin/env python3
"""mksfx_z80.py -- the sound data for the Z80 machines' engine
(src/sound/snd.asm): the effects (the Intellivision's src/intv/sfx.asm,
heard and approved) and the tunes (music/*.txt through tools/mus.py and
the Intellivision's voicing, tools/mkmus_intv.py), as tools/mksfx_coco.py
makes the CoCo's, in z80asm.

    mksfx_z80.py sfx OUT.asm
    mksfx_z80.py tunes OUT.asm NAME=music/x.txt ...

The units are the chips' own and the same on both: a tone's period P is
111861 / Hz (the SN76489's N at 3.58 MHz, the AY's period at 1.79 MHz, the
Intellivision's), a noise's period n (1-31) a new random bit every n of
those (111861 / n a second); the volume 0-15 the AY's, 3 dB a step (the
back end makes it the chip's). A period past 1023 (under 109 Hz) is the
back end's to sound (the SN76489's periodic noise, clocked by its third
tone: true bass).

An effect: steps of jiffies (0 ends it), then the volume (bits 0-3) with
bit 4 noise and bit 5 the envelope (the volume 15, falling), the period
(low, high); with the envelope, its fall in volume steps a jiffy (8.8:
low, high). The cue tables: _sx_cues (16 SND_*: the body, the low end),
_sx_booms (4 sizes: body, low end), _sx_ui (6 UI_*).

A tune: a word a step (little-endian): bits 0-6 the code (an index into
_mus_per, 0 silent; or 112 + n: noise, _mus_nz[n]), 7-10 the volume,
11-15 the jiffies; jiffies 0 a control: 0 returns, 1 calls and 2 jumps
(the next word an address), 3 ends. A tune's channels start at _t_NAME1,
_t_NAME2.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from mksfx_coco import tables, value, SX_N, SX_E  # noqa: E402

CLOCK = 111861.0                # 3579545 / 32 = 1789773 / 16


def rows(lines, label, data, kind="defb"):
    lines.append("%s:" % label)
    per = 16 if kind == "defb" else 8
    for k in range(0, len(data), per):
        lines.append("        %s    %s" % (kind, ", ".join(str(b) for b in data[k:k + per])))


def effect(words):
    vals = [value(t) for t in words]
    out, i = [], 0
    while True:
        what, how = vals[i], vals[i + 1]
        i += 2
        if how == 0:
            out.append(0)
            return out
        jif, vol = (how >> 4) & 255, how & 15
        flags = 0x10 if what & SX_N else 0
        per = (what & 31) if what & SX_N else (what & 0x0FFF)
        if what & SX_E:
            ep = vals[i]
            i += 1
            dv = min(15 * 256, round(16 * 16.667 / (ep * 0.143) * 256))
            out += [jif, 15 | flags | 0x20, per & 255, per >> 8, dv & 255, dv >> 8]
        else:
            out += [jif, vol | flags, per & 255, per >> 8]


def sfx(src, dst):
    t = tables(src)
    fx = [n for n in t if n.startswith("sx_") and n not in ("sx_cues", "sx_booms", "sx_ui")]
    lines = ["; GENERATED by tools/mksfx_z80.py from %s: edit that, not this." % os.path.relpath(src),
             "        SECTION rodata_user",
             "        PUBLIC  _sx_cues, _sx_booms, _sx_ui"]
    n = 0
    for name in fx:
        b = effect(t[name])
        n += len(b)
        rows(lines, name, b)
    for tab in ("sx_cues", "sx_booms", "sx_ui"):
        words = [w.strip() for w in t[tab]]
        n += 2 * len(words)
        rows(lines, "_" + tab, words, "defw")
    open(dst, "w").write("\n".join(lines) + "\n")
    print("%s: %d effects, %d bytes" % (dst, len(fx), n))


def tunes(dst, specs):
    import mus
    import mkmus_intv as mi
    pitches = {None: 0}
    noises = {}
    lines, exports, total = [], [], 0

    def steps(evs, ch):
        res = []
        for hz, v, nz in (mi.voice(e, ch) for e in evs):
            if nz:
                noises.setdefault(nz, 0)
                code = mi.NOISE0 + nz
            else:
                if hz not in pitches:
                    pitches[hz] = len(pitches)
                code = pitches[hz]
            if res and res[-1][0] == code and res[-1][1] == v and res[-1][2] < mi.MAXN:
                res[-1][2] += 1
            else:
                res.append([code, v, 1])
        return [c | v << 7 | n << 11 for c, v, n in res]

    for name, src in specs:
        song = mus.parse(src)
        subs = [{}, {}]
        order = [[], []]
        for pat in song.order:
            for ch in (0, 1):
                key = tuple(steps(mus.frames(song, pat, ch + 1), ch))
                if key not in subs[ch]:
                    subs[ch][key] = "%s_%d_%d" % (name, ch + 1, len(subs[ch]))
                order[ch].append(subs[ch][key])
        for ch in (0, 1):
            top = "_t_%s%d" % (name, ch + 1)
            exports.append(top)
            lines.append("%s:" % top)
            for k, lab in enumerate(order[ch]):
                lines.append("%s_o%d_%d: defw %d, %s" % (name, ch + 1, k, mi.CALL, lab))
                total += 4
            if song.loop is None:
                lines.append("        defw    %d, 0" % mi.END)
            else:
                lines.append("        defw    %d, %s_o%d_%d" % (mi.JUMP, name, ch + 1, song.loop))
            total += 4
        for ch in (0, 1):
            for key, lab in subs[ch].items():
                words = list(key) + [mi.RET]
                total += 2 * len(words)
                rows(lines, lab, words, "defw")
    inv = sorted(pitches, key=lambda h: pitches[h])
    per = [0 if hz is None else max(1, min(4095, round(CLOCK / hz))) for hz in inv]
    nz = [n if n in noises else 0 for n in range(16)]
    with open(dst, "w") as f:
        f.write("; GENERATED by tools/mksfx_z80.py from %s: edit those, not this.\n"
                % ", ".join(s for _, s in specs))
        f.write("        SECTION rodata_user\n")
        f.write("        PUBLIC  _mus_per, _mus_nz, %s\n" % ", ".join(exports))
        rl = []
        rows(rl, "_mus_per", per, "defw")
        rows(rl, "_mus_nz", nz)
        f.write("\n".join(rl + lines) + "\n")
    print("%s: %d bytes, %d pitches" % (dst, total + 2 * len(per) + 16, len(per)))


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    what, out = sys.argv[1], sys.argv[2]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    if what == "sfx":
        sfx(os.path.join(HERE, "..", "src", "intv", "sfx.asm"), out)
    elif what == "tunes":
        tunes(out, [a.split("=", 1) for a in sys.argv[3:]])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
