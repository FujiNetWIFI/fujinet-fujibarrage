#!/usr/bin/env bash
# build.sh -- FujiBarrage for the RCA Studio II: an ST2 image for the FujiNet
# cart's protocol 2 (barrage.asm). FujiBlast's src/studio2 build, for this
# tree.
#
#   src/studio2/build.sh                r2r/studio2/barrage.st2
#   OUT=dir R2R=dir                     where the objects and the image go
#   SERVER=host:port                    the server without the lobby's key
#                                       (default fujinet.online:9913)
#   TEST=1                              the rigs' scenes (src/p_test.inc)
#   DEBUG=1                             the rigs' extras (counters)
#   ASL=                                the assembler (default ~/asl/asl)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/studio2}"
R2R="${R2R:-$ROOT/r2r/studio2}"
T="$ROOT/tools/s2"
ASL="${ASL:-$HOME/asl/asl}"
[ -x "$ASL" ] || ASL=$(command -v asl) || { echo "build.sh: no asl (Macroassembler AS)" >&2; exit 1; }
mkdir -p "$OUT" "$R2R"
OUT="$(cd "$OUT" && pwd)"

python3 "$ROOT/tools/chf/mkproto.py" "$ROOT/src/proto.h" "$OUT/proto.inc"
python3 "$T/mktank_s2.py" "$OUT/tankart.inc"
python3 "$T/mktitle_s2.py" "$OUT/title.inc"
python3 "$T/mksnd_s2.py" "$OUT/snd.inc"
SERVER="${SERVER:-fujinet.online:9913}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'DEFSPEC: DB "N:TCP://%s/",0\n' "$SERVER"
} > "$OUT/config.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  echo "DEBUG   EQU ${DEBUG:-0}"
  echo "TEST    EQU ${TEST:-0}"
} > "$OUT/flags.inc"

python3 "$T/checkdup.py" "$HERE"/src/*.inc "$HERE"/rt/*.inc
NBANKS=$((3 + ${TEST:-0}))              # (equ.inc's: BK_BOOT, BK_ROOM, BK_SHOP, TEST's BK_FIX)
banks=()
for b in $(seq 0 $((NBANKS - 1))); do
    (cd "$OUT" && "$ASL" -q -L -U -D BANK=$b -i "$HERE/rt" -i "$HERE/src" -i "$OUT" \
         -o barrage.b$b.p -olist barrage.b$b.lst "$HERE/barrage.asm") || {
        [ "${FITALL:-0}" = 1 ] && continue      # (tools/s2/fit.sh: every bank's listing)
        grep -B2 -A3 "Error\|error" "$OUT/barrage.b$b.lst" | head -40 >&2
        echo "build.sh: asl failed (bank $b: see $OUT/barrage.b$b.lst)" >&2
        exit 1
    }
    python3 "$T/checkrom.py" "$OUT/barrage.b$b.lst" >/dev/null
    python3 "$T/fitcheck.py" "$OUT/barrage.b$b.lst" >/dev/null
    [ "$b" = 0 ] || banks+=(--bank "$OUT/barrage.b$b.p")
done
cp "$OUT/barrage.b0.lst" "$OUT/barrage.lst"            # (the fixed code's symbols: the rigs')
python3 "$T/checkfixed.py" "$OUT"/barrage.b*.p
python3 "$T/checkldr.py" "$HERE"/src/*.inc
python3 "$T/mkst2.py" "$OUT/barrage.b0.p" "$R2R/barrage.st2" "FUJIBARRAGE" "${banks[@]}"
