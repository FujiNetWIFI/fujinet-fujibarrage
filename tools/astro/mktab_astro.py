#!/usr/bin/env python3
"""mktab_astro.py OUT.inc [PREFIX] -- tables the Astrocade's drawing pages
need (zmac 1.3 has no REPT): FROWT, the field's rows' addresses (FIELD +
40 y); BARREL, a tank's barrel: for each angle step of 5 degrees (0-90),
its 4 pixels' (dx, dy) from the turret, src/atari/field.c's barrel() for
square steps (the Astrocade's lines are about as tall as its pixels are
wide); Q32, the ellipses' quarter circle. PREFIX names the copy (each
drawing page has its own: FP_ the PLAY page's, PY_ PLY's, OQ_ OPS's)."""
import math
import sys

out, pre = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "FP_")
lines = ["; GENERATED by tools/astro/mktab_astro.py -- do not edit.", pre + "ROWT:"]
for y in range(56):
    lines.append("        DW      FIELD+%d*BYTEPL" % y)
lines.append(pre + "BARREL:")
for i in range(19):
    a = math.radians(5 * i)
    px = []
    for k in range(1, 5):
        px += [int(k * math.cos(a) + 0.5), int(k * math.sin(a) + 0.5)]
    lines.append("        DB      %s    ; %d" % (",".join(str(v) for v in px), 5 * i))
lines.append(pre + "Q32:          ; a quarter circle: 64 sqrt(1 - (i/32)^2) (src/atari/fld.s's q32)")
lines.append("        DB      64,64,64,63,63,62,62,61,60,59,57,56,54,53,51,49")
lines.append("        DB      46,44,41,38,35,32,28,24,20,15,10,5,0,0,0,0,0")
open(out, "w").write("\n".join(lines) + "\n")
