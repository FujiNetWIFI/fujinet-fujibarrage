#!/usr/bin/env python3
"""mkgfx_nes.py -- the NES's art, written as ca65 data.

    mkgfx_nes.py font OUT.s      the Namco 8x8 font (gfx/coco/namco.bin),
                                 ' ' to '_' (64 glyphs, 8 bytes each, one
                                 bit a pixel): _font8, in CODE2 (R7's bank,
                                 always in: the HUD's letters are drawn
                                 from it while an overlay holds R6)
    mkgfx_nes.py sprites OUT.s   the sprites' 4K ($1000, CHR banks 16-19):
                                 _spr_chr in the ART bank. Tile 0 blank;
                                 1 + 38v + 19p + a/10: the tank at barrel
                                 angle a (0-180), p 1 with your pennant, in
                                 colour 1 + v (a sprite palette's three:
                                 tools/mkgfx_tms.py's drawing); 115-117 a
                                 spark, a pixel in colour 1-3 (its last line)
    mkgfx_nes.py title OUT.s     the title's hills: a column's top line
                                 each (256), _title_hills in FOPEN (bank 7,
                                 src/nes/fieldo.c's field_title)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")


def rows(data, per=16):
    return ["        .byte   " + ", ".join("$%02X" % b for b in data[i:i + per])
            for i in range(0, len(data), per)]


def emit(path, lines):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    open(path, "w").write("; generated by tools/nes/mkgfx_nes.py: do not edit\n" + "\n".join(lines) + "\n")


def font(path):
    glyphs = open(os.path.join(ROOT, "gfx", "coco", "namco.bin"), "rb").read()[0:512]
    emit(path, ['.segment "CODE2"', "        .export _font8", "_font8:"] + rows(glyphs))


def tile2(px):
    """an 8x8 of colours 0-3 as the NES's 16 bytes (plane 0, plane 1)"""
    lo = [sum(((px[y][x] & 1) << (7 - x)) for x in range(8)) for y in range(8)]
    hi = [sum(((px[y][x] >> 1) << (7 - x)) for x in range(8)) for y in range(8)]
    return lo + hi


def sprites(path):
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import mkgfx_tms as mt
    tiles = [[0] * 16]
    for v in range(3):
        for p in (0, 1):
            for a in range(0, 181, 10):
                rows8 = mt.tank(a, p)
                px = [[(v + 1) if (rows8[y] >> (7 - x)) & 1 else 0 for x in range(8)] for y in range(8)]
                tiles.append(tile2(px))
    for v in range(3):                  # 115-117: a spark, one pixel (the last line), colour 1-3
        px = [[0] * 8 for _ in range(8)]
        px[7][0] = v + 1
        tiles.append(tile2(px))
    data = [b for t in tiles for b in t]
    data += [0] * (4096 - len(data))
    emit(path, ['.segment "ART"', "        .export _spr_chr", "_spr_chr:"] + rows(data))


def title(path):
    import math
    tops = []
    for x in range(256):
        h = 128 + 14 * math.sin(x / 37.0) + 9 * math.sin(x / 13.0 + 1.3) - 16 * math.exp(-((x - 128) / 40.0) ** 2)
        tops.append(max(96, min(160, int(round(h)))))
    emit(path, ['.segment "FOPEN"', "        .export _title_hills", "_title_hills:"] + rows(tops))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    what, out = sys.argv[1:]
    {"font": font, "sprites": sprites, "title": title}[what](out)


if __name__ == "__main__":
    main()
