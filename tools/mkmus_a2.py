#!/usr/bin/env python3
"""mkmus_a2.py -- FujiBarrage's tunes (music/*.txt, tools/mus.py) for the
Mockingboard's AY-3-8910 (src/apple2/mock.s): ch1 on voice A, ch2 on B.

The Intellivision's converter (tools/mkmus_intv.py) does the voicing (the
same family of PSG, its volumes 3 dB a step): its steps, with the periods
for the Apple's clock (1020484 Hz: f = 63780 / P). A word a step, as
there: bits 0-6 the code (an index into mus_per, 0 silent; or 112 + n, a
noise drum of period n), bits 7-10 the volume, bits 11-15 the jiffies. A
word with jiffies 0 is a control: code 0 returns, 1 calls and 2 jumps (the
word after it an address), 3 ends a tune played once.

usage: mkmus_a2.py OUT.s NAME=music/x.txt ...
  (each tune's channels start at _NAME1 and _NAME2: sound.h's t_*1, t_*2)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mus  # noqa: E402
import mkmus_intv as mi  # noqa: E402

CLOCK = 1020484.0 / 16


def main():
    out = sys.argv[1]
    tunes = [a.split("=", 1) for a in sys.argv[2:]]
    pitches = {None: 0}
    lines = []
    exports = []

    def steps(evs, ch):
        res = []
        for hz, v, nz in (mi.voice(e, ch) for e in evs):
            if hz not in pitches:
                pitches[hz] = len(pitches)
            code = mi.NOISE0 + nz if nz else pitches[hz]
            if res and res[-1][0] == code and res[-1][1] == v and res[-1][2] < mi.MAXN:
                res[-1][2] += 1
            else:
                res.append([code, v, 1])
        return [c | v << 7 | n << 11 for c, v, n in res]

    total = 0
    for name, src in tunes:
        song = mus.parse(src)
        subs = [{}, {}]
        order = [[], []]
        for pat in song.order:
            lens = set()
            for ch in (0, 1):
                evs = mus.frames(song, pat, ch + 1)
                lens.add(len(evs))
                key = tuple(steps(evs, ch))
                if key not in subs[ch]:
                    subs[ch][key] = "%s_%d_%d" % (name, ch + 1, len(subs[ch]))
                order[ch].append(subs[ch][key])
            if len(lens) != 1:
                raise SystemExit("%s: pattern %s's channels differ in length" % (src, pat))
        for ch in (0, 1):
            top = "_%s%d" % (name, ch + 1)
            exports.append(top)
            lines.append("%s:" % top)
            for k, lab in enumerate(order[ch]):
                lines.append("%s_o%d_%d: .word %d, %s" % (name, ch + 1, k, mi.CALL, lab))
                total += 4
            if song.loop is None:
                lines.append("        .word   %d, 0" % mi.END)
            else:
                lines.append("        .word   %d, %s_o%d_%d" % (mi.JUMP, name, ch + 1, song.loop))
            total += 4
        for ch in (0, 1):
            for key, lab in subs[ch].items():
                words = list(key) + [mi.RET]
                total += 2 * len(words)
                lines.append("%s:" % lab)
                for i in range(0, len(words), 12):
                    lines.append("        .word   %s" % ", ".join(str(w) for w in words[i:i + 12]))
        jiffies = sum(len(song.patterns[n]) for n in song.order) * song.tempo
        print("%s: %d bars, %.1f s, %s" % (src, len(song.order), jiffies / 60,
                                           "once" if song.loop is None else "loops"))
    if len(pitches) > mi.NOISE0:
        raise SystemExit("%d pitches: past the noise codes" % len(pitches))
    inv = sorted(pitches, key=lambda h: pitches[h])
    per = [1 if hz is None else max(1, min(4095, round(CLOCK / hz))) for hz in inv]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as f:
        f.write("; GENERATED by tools/mkmus_a2.py from %s: edit those, not this.\n"
                % ", ".join(src for _, src in tunes))
        f.write("; A word a step (src/apple2/mock.s plays them): the code (a period's\n"
                "; index in mus_per, or %d + a noise period), the volume << 7, the\n"
                "; jiffies << 11; jiffies 0 a control: 0 return, 1 call, 2 jump (the\n"
                "; next word where), 3 the end.\n" % mi.NOISE0)
        f.write("        .export mus_per, %s\n" % ", ".join(exports))
        f.write("        .rodata\nmus_per:\n")
        for i in range(0, len(per), 12):
            f.write("        .word   %s\n" % ", ".join(str(p) for p in per[i:i + 12]))
        f.write("\n".join(lines) + "\n")
    print("%s: %d bytes, %d pitches" % (out, total + 2 * len(per), len(per)))


if __name__ == "__main__":
    main()
